# Fair fight: psi' = U psi (one SU(3) matrix times one color vector) on the
# project's RV32I cores vs AxISA's single SU3MUL instruction.
# Run from hardware/bench:  python gen_bench_su3mul.py && (see README.md)
#
# Same matrix, same vector, same binary32 rounding order (tRe = fl(fl(ac) -
# fl(bd)), tIm = fl(fl(ad) + fl(bc)), accumulated over j = 0, 1, 2), so
# every output word must match AxISA's reference model bit for bit - the
# checks come from tools/gen_su3mul_test.py's model, not from either core.
#
# The RV32I program is the best straight-line code I can write by hand
# for these cores' RV32F subset (FLW/FSW/FADD.S/FSUB.S/FMUL.S, no FMA):
# fully unrolled, no loop, no address arithmetic. Row i's accumulator
# starts as the j = 0 term itself (fl(+0 + t) = t for these values), so
# it does one fewer add per row than AxISA does - in RV32I's favour.
import contextlib
import io
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AX = os.path.join(HERE, '..', 'axisa_core')
RV = os.path.join(HERE, '..', 'rv32i_core')
import importlib.util  # noqa: E402
# both projects call their encoder module asm_test1 - load RV32I's under another name
_spec = importlib.util.spec_from_file_location('rv32i_asm', os.path.join(RV, 'sw', 'asm_test1.py'))
rv = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rv)

cwd = os.getcwd()
os.chdir(AX)
sys.path.insert(0, os.path.join(AX, 'sw'))
sys.path.insert(0, os.path.join(AX, 'tools'))
with contextlib.redirect_stdout(io.StringIO()):
    import gen_su3mul_test as g   # noqa: E402  (also rewrites its own test files - deterministic)
os.chdir(cwd)

U, PSI = g.M1, g.PSI_A
OUT = g.ref_su3mul(U, PSI)
bits = g.bits

U_ADDR, PSI_ADDR, OUT_ADDR = 0x100, 0x200, 0x300
# f0..f5 = psi (Re, Im per color); f12/f13 = a, b; f6..f9 products; f10/f11 acc; f14/f15 term
prog = []
for j in range(3):
    prog += [rv.flw(2 * j, PSI_ADDR + 8 * j, 0), rv.flw(2 * j + 1, PSI_ADDR + 8 * j + 4, 0)]
for i in range(3):
    for j in range(3):
        e = U_ADDR + 8 * (3 * i + j)
        c, d = 2 * j, 2 * j + 1
        prog += [rv.flw(12, e, 0), rv.flw(13, e + 4, 0),
                 rv.fmul_s(6, 12, c), rv.fmul_s(7, 13, d), rv.fmul_s(8, 12, d), rv.fmul_s(9, 13, c)]
        if j == 0:
            prog += [rv.fsub_s(10, 6, 7), rv.fadd_s(11, 8, 9)]
        else:
            prog += [rv.fsub_s(14, 6, 7), rv.fadd_s(15, 8, 9), rv.fadd_s(10, 10, 14), rv.fadd_s(11, 11, 15)]
    prog += [rv.fsw(10, OUT_ADDR + 8 * i, 0), rv.fsw(11, OUT_ADDR + 8 * i + 4, 0)]
N_KERNEL = len(prog)
prog += [rv.lw(10, OUT_ADDR, 0), rv.ecall()]
with open(os.path.join(HERE, 'su3mul_rv32i.hex'), 'w') as f:
    for w in prog:
        f.write("%08x\n" % (w & 0xFFFFFFFF))

pre = []
for i in range(3):
    for j in range(3):
        for k, v in ((0, U[i][j].real), (4, U[i][j].imag)):
            pre.append((U_ADDR + 8 * (3 * i + j) + k, bits(v)))
for j in range(3):
    pre += [(PSI_ADDR + 8 * j, bits(PSI[j][0])), (PSI_ADDR + 8 * j + 4, bits(PSI[j][1]))]


def tb(module, name):
    L = [f"""// GENERATED by hardware/bench/gen_bench_su3mul.py - U psi on {module}.
`timescale 1ns/1ps
module {name};
    reg clk, reset;
    wire halted;
    wire [31:0] tohost_value;
    integer cycle_count, errors;
    {module} #(.INSTR_MEM_WORDS(1024), .INSTR_INIT_FILE("su3mul_rv32i.hex"), .DATA_MEM_BYTES(4096)) dut (
        .clk(clk), .reset(reset), .halted(halted), .tohost_value(tohost_value),
        .bus_grant(1'b1), .bus_read_data(32'b0)
    );
    always #5 clk = ~clk;
    task poke(input integer addr, input [31:0] v);
        begin
            dut.dmem.mem0[addr / 4] = v[7:0];   dut.dmem.mem1[addr / 4] = v[15:8];
            dut.dmem.mem2[addr / 4] = v[23:16]; dut.dmem.mem3[addr / 4] = v[31:24];
        end
    endtask
    task check(input integer addr, input [31:0] v);
        reg [31:0] got;
        begin
            got = {{dut.dmem.mem3[addr / 4], dut.dmem.mem2[addr / 4], dut.dmem.mem1[addr / 4], dut.dmem.mem0[addr / 4]}};
            if (got !== v) begin $display("FAIL: @%0h got %h expected %h", addr, got, v); errors = errors + 1; end
        end
    endtask
    initial begin
        clk = 0; reset = 1; cycle_count = 0; errors = 0;
        @(posedge clk); @(posedge clk);"""]
    L += [f"        poke({a}, 32'h{v:08X});" for a, v in pre]
    L.append("""        reset = 0;
        while (!halted && cycle_count < 5000) begin @(posedge clk); cycle_count = cycle_count + 1; end""")
    for i, (re_, im_) in enumerate(OUT):
        L.append(f"        check({OUT_ADDR + 8 * i}, 32'h{bits(re_):08X}); check({OUT_ADDR + 8 * i + 4}, 32'h{bits(im_):08X});")
    L.append(f"""        $display("{module}: halted after %0d cycles ({N_KERNEL} kernel instructions + LW + ECALL)", cycle_count);
        if (errors == 0) $display("PASS: psi' bit-exact with AxISA's SU3MUL reference model");
        $finish;
    end
endmodule
""")
    with open(os.path.join(HERE, name + '.v'), 'w') as f:
        f.write("\n".join(L))


tb('cpu_core', 'tb_bench_rv32i_single')
tb('cpu_core_pipelined', 'tb_bench_rv32i_pipe')
print(f"RV32I kernel: {N_KERNEL} instructions")
