# Fair fight 2: von Neumann vs compute-in-memory, on the SAME AxISA core.
# Three jobs on 64 words (w[i] = 3i - 50):
#   SUM    the sum of all words                     (2848)
#   COUNT  how many words are negative              (17)
#   ADD    add 100 to every word, in place
# Von Neumann: the words are in data memory and the core does it the
# usual way - fully unrolled straight-line LOAD/ALU/STORE code, no loop,
# no address arithmetic (every advantage to the classic side).
# CIM: the same words are in the CIM block: CIM.SUM, CIM.FINDLT, CIM.ADD.
# Setup (filling both) is not timed. Each job sits between two UART
# writes; tb_cim_bench.v counts the cycles between them.
# Writes cim/cim_bench.axasm and assembles it to cim/cim_bench.hex.
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "cim")
BASE = 0x400
L = []
a = L.append

a("# GENERATED by hardware/bench/gen_bench_cim.py - see there")
a("    ADDI N1, N0, 0")
a("    ADDI N2, N0, -50")
a("    ADDI N3, N0, 64")
a("    ADDI N5, N0, %d" % BASE)
a("fill:")
a("    STORE N2, N5, 0          # data memory")
a("    CIM.PUT N1, N2           # and the CIM block")
a("    ADDI N2, N2, 3")
a("    ADDI N1, N1, 1")
a("    ADDI N5, N5, 4")
a("    BNE N1, N3, fill")


def mark():
    a("    STORE N0, N0, 0x1000     # UART: timing mark")


mark()
a("# --- SUM, von Neumann")
a("    ADDI N4, N0, 0")
for i in range(64):
    a("    LOAD N2, N0, %d" % (BASE + 4 * i))
    a("    ADD N4, N4, N2")
a("    STORE N4, N0, 0x300")
mark()
a("# --- SUM, CIM")
a("    CIM.SUM N4")
a("    STORE N4, N0, 0x304")
mark()
a("# --- COUNT negative, von Neumann")
a("    ADDI N4, N0, 0")
for i in range(64):
    a("    LOAD N2, N0, %d" % (BASE + 4 * i))
    a("    SLTI N2, N2, 0")
    a("    ADD N4, N4, N2")
a("    STORE N4, N0, 0x308")
mark()
a("# --- COUNT negative, CIM")
a("    CIM.FINDLT N4, N0")
a("    STORE N4, N0, 0x30C")
mark()
a("# --- ADD 100 to every word, von Neumann")
for i in range(64):
    a("    LOAD N2, N0, %d" % (BASE + 4 * i))
    a("    ADDI N2, N2, 100")
    a("    STORE N2, N0, %d" % (BASE + 4 * i))
mark()
a("# --- ADD 100 to every word, CIM")
a("    ADDI N6, N0, 100")
a("    CIM.ADD N6")
mark()
a("    HALT N0")

os.makedirs(OUT, exist_ok=True)
src = os.path.join(OUT, "cim_bench.axasm")
open(src, "w").write("\n".join(L) + "\n")
asm = os.path.join(HERE, "..", "axisa_core", "sw", "axasm.py")
subprocess.run([sys.executable, asm, src, os.path.join(OUT, "cim_bench.hex")], check=True)
