# Energy per U psi on the synthesized (gate-level) AxISA and RV32I netlists.
# Run from hardware/bench:  python gen_bench_energy.py
#
# Gate-level netlists have no named memories to preload, so every program
# writes its own data first. Two programs per core:
#   A = setup + check + halt          B = setup + U psi + check + halt
# The energy of U psi is E(B) - E(A), E = average power x run time, power
# from OpenROAD report_power with the run's own VCD (100 ns clock, as in the
# SDC). The subtraction cancels each ISA's own way of setting data up.
# Same matrix and vector as the cycle bench (gen_su3mul_test.py's M1, PSI_A).
#
# Writes energy/{axisa,rv32i}_{A,B}.{axasm,hex}, energy/expect.txt and the
# two testbenches energy/tb_energy_{axisa,rv32i}.v (they drive the ASIC
# wrappers' load port; the same files run on RTL and on the netlists).
import contextlib
import importlib.util
import io
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AX = os.path.join(HERE, '..', 'axisa_core')
RV = os.path.join(HERE, '..', 'rv32i_core')
OUTD = os.path.join(HERE, 'energy')
os.makedirs(OUTD, exist_ok=True)

_spec = importlib.util.spec_from_file_location('rv32i_asm', os.path.join(RV, 'sw', 'asm_test1.py'))
rv = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rv)
cwd = os.getcwd()
os.chdir(AX)
sys.path.insert(0, os.path.join(AX, 'sw'))
sys.path.insert(0, os.path.join(AX, 'tools'))
with contextlib.redirect_stdout(io.StringIO()):
    import gen_su3mul_test as g   # noqa: E402
os.chdir(cwd)

U, PSI, OUT = g.M1, g.PSI_A, g.ref_su3mul(g.M1, g.PSI_A)
bits = g.bits
IMEM_WORDS = 256
expect = {}

# ---------------- AxISA ----------------
AX_U = 0x100


def ax_load32(reg, v, clear=None):
    z = reg[0] + "0" if reg[0] == 'N' else reg
    pre = [clear] if clear else []
    return pre + [f"ADDI {reg}, {z}, {v >> 21}", f"SLLI {reg}, {reg}, 11", f"ORI {reg}, {reg}, {(v >> 10) & 0x7FF}",
                  f"SLLI {reg}, {reg}, 10", f"ORI {reg}, {reg}, {v & 0x3FF}"]


def axisa_prog(with_kernel):
    a = [f"# GENERATED by hardware/bench/gen_bench_energy.py - AxISA energy program {'B (with SU3MUL)' if with_kernel else 'A (setup only)'}"]
    for i in range(3):
        for j in range(3):
            for k, v in ((0, U[i][j].real), (4, U[i][j].imag)):
                a += ax_load32("N1", bits(v)) + [f"STORE N1, N0, 0x{AX_U + 8 * (3 * i + j) + k:X}"]
    # psi into pair 0; pair 2 cleared. Color banks have no zero register and a
    # gate-level netlist starts with X in them, so AND with 0 first.
    for bank, (re_, im_) in zip("RGB", PSI):
        a += ax_load32(f"{bank}0", bits(re_), f"ANDI {bank}0, {bank}0, 0")
        a += ax_load32(f"{bank}1", bits(im_), f"ANDI {bank}1, {bank}1, 0")
        a += [f"ANDI {bank}2, {bank}2, 0", f"ANDI {bank}3, {bank}3, 0"]
    a.append(f"ADDI N2, N0, 0x{AX_U:X}")
    a.append("SU3MUL N2, 2, 0" if with_kernel else "ADDI N0, N0, 0          # (no SU3MUL)")
    a += ["BARYON SUM, N3, R2, G2, B2", "BARYON SUM, N4, R3, G3, B3", "ADD N5, N3, N4", "HALT N5", ""]
    return "\n".join("    " + x if not x.startswith("#") and x else x for x in a)


chk = sum(bits(re_) + bits(im_) for re_, im_ in OUT) & 0xFFFFFFFF
for name, k in (("A", False), ("B", True)):
    src = os.path.join(OUTD, f"axisa_{name}.axasm")
    open(src, 'w', encoding='utf-8').write(axisa_prog(k))
    subprocess.run([sys.executable, os.path.join(AX, 'sw', 'axasm.py'), src, os.path.join(OUTD, f"axisa_{name}.hex")],
                   check=True, capture_output=True)
    n = sum(1 for _ in open(os.path.join(OUTD, f"axisa_{name}.hex")))
    assert n <= IMEM_WORDS, n
    expect[f"axisa_{name}"] = chk if k else 0

# ---------------- RV32I ----------------
RV_U, RV_PSI, RV_OUT = 0x000, 0x050, 0x080


def rv_store32(v, addr):
    lo = v & 0xFFF
    if lo & 0x800:
        lo -= 0x1000
    hi = ((v - lo) >> 12) & 0xFFFFF
    return [rv.lui(1, hi), rv.addi(1, 1, lo), rv.sw(1, addr, 0)]


def rv32i_prog(with_kernel):
    p = []
    for i in range(3):
        for j in range(3):
            p += rv_store32(bits(U[i][j].real), RV_U + 8 * (3 * i + j))
            p += rv_store32(bits(U[i][j].imag), RV_U + 8 * (3 * i + j) + 4)
    for j in range(3):
        p += rv_store32(bits(PSI[j][0]), RV_PSI + 8 * j) + rv_store32(bits(PSI[j][1]), RV_PSI + 8 * j + 4)
    p.append(rv.sw(0, RV_OUT, 0))                       # the checked word starts as 0
    if with_kernel:                                     # gen_bench_su3mul.py's unrolled kernel
        for j in range(3):
            p += [rv.flw(2 * j, RV_PSI + 8 * j, 0), rv.flw(2 * j + 1, RV_PSI + 8 * j + 4, 0)]
        for i in range(3):
            for j in range(3):
                e = RV_U + 8 * (3 * i + j)
                c, d = 2 * j, 2 * j + 1
                p += [rv.flw(12, e, 0), rv.flw(13, e + 4, 0),
                      rv.fmul_s(6, 12, c), rv.fmul_s(7, 13, d), rv.fmul_s(8, 12, d), rv.fmul_s(9, 13, c)]
                if j == 0:
                    p += [rv.fsub_s(10, 6, 7), rv.fadd_s(11, 8, 9)]
                else:
                    p += [rv.fsub_s(14, 6, 7), rv.fadd_s(15, 8, 9), rv.fadd_s(10, 10, 14), rv.fadd_s(11, 11, 15)]
            p += [rv.fsw(10, RV_OUT + 8 * i, 0), rv.fsw(11, RV_OUT + 8 * i + 4, 0)]
    p += [rv.lw(10, RV_OUT, 0), rv.ecall()]
    return p


for name, k in (("A", False), ("B", True)):
    prog = rv32i_prog(k)
    assert len(prog) <= IMEM_WORDS, len(prog)
    with open(os.path.join(OUTD, f"rv32i_{name}.hex"), 'w') as f:
        for w in prog:
            f.write("%08x\n" % (w & 0xFFFFFFFF))
    expect[f"rv32i_{name}"] = bits(OUT[0][0]) if k else 0

with open(os.path.join(OUTD, "expect.txt"), 'w') as f:
    for k, v in expect.items():
        f.write(f"{k} {v}\n")

# ---------------- testbenches (RTL wrapper or gate-level netlist) ----------------
TB = """// GENERATED by hardware/bench/gen_bench_energy.py - energy run on the {core}
// ASIC wrapper (RTL or gate-level netlist). +HEX=<program> +EXPECT=<tohost>
// +VCD=<file>. The program is written through the load port while reset is
// held; the VCD covers reset release to HALT only, at the SDC's 100 ns clock.
`timescale 1ns/1ps
module tb_energy_{core};
    reg clk, reset, we;
    reg [31:0] la, ld, expect_v;
    reg [31:0] prog [0:{words_m1}];
    reg [8*128-1:0] hexfile, vcdfile;
    wire halted;
    wire [31:0] tohost_value;
    integer cycle_count, k;
    cpu_core_top dut (
        .clk(clk), .reset(reset), .imem_load_we(we), .imem_load_addr(la), .imem_load_data(ld),
        .halted(halted), .tohost_value(tohost_value),
{ties}
    );
    always #50 clk = ~clk;   // 100 ns, the SDC's clock
    initial begin
        if (!$value$plusargs("HEX=%s", hexfile)) hexfile = "prog.hex";
        if (!$value$plusargs("VCD=%s", vcdfile)) vcdfile = "energy.vcd";
        if (!$value$plusargs("EXPECT=%d", expect_v)) expect_v = 0;
        clk = 0; reset = 1; we = 0; la = 0; ld = 0; cycle_count = 0;
        for (k = 0; k <= {words_m1}; k = k + 1) prog[k] = 32'h{nop};
        $readmemh(hexfile, prog);
        for (k = 0; k <= {words_m1}; k = k + 1) begin
            @(negedge clk); we = 1; la = 4 * k; ld = prog[k];
        end
        @(negedge clk); we = 0;
        @(negedge clk); @(negedge clk);
        $dumpfile(vcdfile);
        $dumpvars(0, dut);
        reset = 0;
        while (!halted && cycle_count < 20000) begin @(posedge clk); cycle_count = cycle_count + 1; end
        $dumpflush;
        $display("ENERGY-RUN cycles=%0d tohost=%0d expect=%0d", cycle_count, tohost_value, expect_v);
        if (halted && tohost_value === expect_v) $display("ENERGY-RUN PASS");
        else $display("ENERGY-RUN FAIL");
        $finish;
    end
endmodule
"""
ax_ties = """        .irq_in(1'b0), .bus_req(), .bus_addr(), .bus_write_data(), .bus_mem_write(), .bus_mem_size(), .bus_mem_unsigned(),
        .bus_grant(1'b0), .bus_read_data(32'b0), .uart_tx_valid(), .uart_tx_data(),
        .uart_rx_data_in(8'b0), .uart_rx_ready_in(1'b0), .uart_rx_ack(),
        .hop_out_valid(), .hop_out_data(), .hop_out_ready(4'b0), .hop_in_valid(4'b0), .hop_in_data(128'b0), .hop_in_ready()"""
rv_ties = """        .page_fault(), .bus_req(), .bus_addr(), .bus_write_data(), .bus_mem_write(), .bus_mem_size(), .bus_mem_unsigned(),
        .bus_grant(1'b1), .bus_read_data(32'b0)"""
for core, ties, nop in (("axisa", ax_ties, "0e000000"), ("rv32i", rv_ties, "00000013")):
    with open(os.path.join(OUTD, f"tb_energy_{core}.v"), 'w') as f:
        f.write(TB.format(core=core, ties=ties, nop=nop, words_m1=IMEM_WORDS - 1))
for k, v in expect.items():
    print(f"{k:8s} expect tohost {v}")
