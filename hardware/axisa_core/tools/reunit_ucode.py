# REUNIT's microprogram (AxISA v2.3 step 2) - the single source of truth.
# `python tools/reunit_ucode.py` writes rtl/reunit_rom.v from it, and
# tools/gen_reunit_test.py runs the very same list as its binary32
# reference model, so the RTL and the model cannot drift apart.
#
# Scratch registers: S0..S17 = the matrix, row-major (row i, column j:
# Re at 6i + 2j, Im at 6i + 2j + 1); S18.. = temporaries; operand 31 reads
# the constant 1.0. Rows: u = row 0, v = row 1, w = row 2.
#
#   1. u <- u / |u|
#   2. v <- v - (u^dag v) u          (Gram-Schmidt: v orthogonal to u)
#   3. v <- v / |v|
#   4. w <- conj(u x v)              (det = 1 and w orthogonal to both)
import os

MUL, ADD, SUB, SQRT, DIV, END = 0, 1, 2, 3, 4, 7
ONE = 31
NAMES = {MUL: 'MUL', ADD: 'ADD', SUB: 'SUB', SQRT: 'SQRT', DIV: 'DIV', END: 'END'}


def re(row, col):
    return 6 * row + 2 * col


def im(row, col):
    return 6 * row + 2 * col + 1


T0, T1, T2, PR, PI = 18, 19, 20, 21, 22   # temporaries
N_SCRATCH = 23

prog = []


def op(o, d, a, b=0):
    prog.append((o, d, a, b))


def normalize(row):
    # T0 = sum of |x_k|^2, in the order Re0 Im0 Re1 Im1 Re2 Im2
    op(MUL, T0, re(row, 0), re(row, 0))
    for k in range(6)[1:]:
        r = 6 * row + k
        op(MUL, T1, r, r)
        op(ADD, T0, T0, T1)
    op(SQRT, T0, T0)
    op(DIV, T0, ONE, T0)            # 1 / |x|
    for k in range(6):
        op(MUL, 6 * row + k, 6 * row + k, T0)


def cmul(dre, dim, ar, ai, br, bi):
    """(ar + i ai)(br + i bi) -> dre, dim (uses T1, T2)."""
    op(MUL, T1, ar, br)
    op(MUL, T2, ai, bi)
    op(SUB, dre, T1, T2)
    op(MUL, T1, ar, bi)
    op(MUL, T2, ai, br)
    op(ADD, dim, T1, T2)


normalize(0)
# p = u^dag v = sum_k conj(u_k) v_k:  Re += ur vr + ui vi,  Im += ur vi - ui vr
op(MUL, PR, re(0, 0), re(1, 0))
op(MUL, T1, im(0, 0), im(1, 0))
op(ADD, PR, PR, T1)
op(MUL, PI, re(0, 0), im(1, 0))
op(MUL, T1, im(0, 0), re(1, 0))
op(SUB, PI, PI, T1)
for k in (1, 2):
    op(MUL, T1, re(0, k), re(1, k))
    op(ADD, PR, PR, T1)
    op(MUL, T1, im(0, k), im(1, k))
    op(ADD, PR, PR, T1)
    op(MUL, T1, re(0, k), im(1, k))
    op(ADD, PI, PI, T1)
    op(MUL, T1, im(0, k), re(1, k))
    op(SUB, PI, PI, T1)
# v_k -= p u_k
for k in range(3):
    op(MUL, T1, PR, re(0, k))
    op(MUL, T2, PI, im(0, k))
    op(SUB, T1, T1, T2)
    op(SUB, re(1, k), re(1, k), T1)
    op(MUL, T1, PR, im(0, k))
    op(MUL, T2, PI, re(0, k))
    op(ADD, T1, T1, T2)
    op(SUB, im(1, k), im(1, k), T1)
normalize(1)
# w = conj(u x v): w_a = conj(u_b v_c - u_c v_b) for (a, b, c) = (0,1,2), (1,2,0), (2,0,1)
for a, b, c in ((0, 1, 2), (1, 2, 0), (2, 0, 1)):
    cmul(PR, PI, re(0, b), im(0, b), re(1, c), im(1, c))          # u_b v_c
    cmul(T0, re(2, a), re(0, c), im(0, c), re(1, b), im(1, b))    # u_c v_b (Im parked in w_a Re)
    op(SUB, im(2, a), re(2, a), PI)                               # Im w_a = Im(u_c v_b) - Im(u_b v_c)
    op(SUB, re(2, a), PR, T0)                                     # Re w_a = Re(u_b v_c) - Re(u_c v_b)
op(END, 0, 0, 0)

N_ARITH = sum(1 for o, *_ in prog if o in (MUL, ADD, SUB))
N_ROOT = sum(1 for o, *_ in prog if o in (SQRT, DIV))
assert all(d < N_SCRATCH and (a < N_SCRATCH or a == ONE) and (b < N_SCRATCH or b == ONE) for _, d, a, b in prog)


def run(s, f32, fsqrt):
    """Execute the microprogram on a list of 23 binary32 values (the model)."""
    s = list(s)
    rd = lambda i: 1.0 if i == ONE else s[i]
    for o, d, a, b in prog:
        if o == END:
            break
        x, y = rd(a), rd(b)
        s[d] = {MUL: lambda: f32(x * y), ADD: lambda: f32(x + y), SUB: lambda: f32(x - y),
                SQRT: lambda: fsqrt(x), DIV: lambda: f32(x / y)}[o]()
    return s


def write_rom(path):
    lines = ["// GENERATED by tools/reunit_ucode.py - do not edit. REUNIT's microprogram",
             f"// (AxISA v2.3 step 2): {len(prog)} micro-ops, {N_ARITH} add/sub/mul + {N_ROOT} sqrt/div.",
             "// Word = {op[2:0], dst[4:0], a[4:0], b[4:0]}; op 0 MUL, 1 ADD, 2 SUB, 3 SQRT,",
             "// 4 DIV, 7 END; operand 31 reads 1.0. See the comments in the .py file.",
             "`timescale 1ns/1ps", "", "module reunit_rom (", "    input  wire [7:0]  addr,",
             "    output reg  [17:0] word", ");", "    always @(*) begin", "        case (addr)"]
    for i, (o, d, a, b) in enumerate(prog):
        lines.append(f"            8'd{i}: word = {{3'd{o}, 5'd{d}, 5'd{a}, 5'd{b}}}; // {NAMES[o]}")
    lines += ["            default: word = {3'd7, 15'd0};", "        endcase", "    end", "endmodule", ""]
    open(path, 'w', encoding='utf-8', newline='').write("\n".join(lines))


if __name__ == '__main__':
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    write_rom('rtl/reunit_rom.v')
    print(f"rtl/reunit_rom.v: {len(prog)} micro-ops ({N_ARITH} arithmetic, {N_ROOT} sqrt/div), {N_SCRATCH} scratch registers")
