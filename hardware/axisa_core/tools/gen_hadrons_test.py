# Generates sw/hadrons_test.axasm + tb/tb_hadrons.v. Expected values come
# from the physics tables below (PDG quark quantum numbers), NOT from the RTL.
import sys
# flavor: (charge in thirds, S, C, B', T, 2*I3)
Q = {'UP': (2, 0, 0, 0, 0, 1), 'DOWN': (-1, 0, 0, 0, 0, -1), 'STRANGE': (-1, -1, 0, 0, 0, 0),
     'CHARM': (2, 0, 1, 0, 0, 0), 'BOTTOM': (-1, 0, 0, -1, 0, 0)}
# no TOP: the top quark decays before it can hadronize - QN traps on it
def qn(quarks):  # quarks: list of (flavor, anti)
    tot = [0]*6
    for f, anti in quarks:
        for i, v in enumerate(Q[f]):
            tot[i] += -v if anti else v
    assert tot[0] % 3 == 0
    nq = sum(1 for _, a in quarks if not a); na = len(quarks) - nq
    B = (nq - na) // 3
    fields = [tot[0]//3, B, tot[1], tot[2], tot[3], tot[4], tot[5]]
    w = 0
    for i, v in enumerate(fields):
        assert -8 <= v <= 7
        w |= (v & 0xF) << (4*i)
    return w, fields
def tok(f, anti): return ('-' if anti else '') + f
baryons = [  # name, (r,g,b)
    ("proton uud",      [('UP',0),('UP',0),('DOWN',0)]),
    ("neutron udd",     [('UP',0),('DOWN',0),('DOWN',0)]),
    ("Delta++ uuu",     [('UP',0),('UP',0),('UP',0)]),
    ("Omega- sss",      [('STRANGE',0)]*3),
    ("Lambda uds",      [('UP',0),('DOWN',0),('STRANGE',0)]),
    ("Lambda_c+ udc",   [('UP',0),('DOWN',0),('CHARM',0)]),
    ("Lambda_b udb",    [('UP',0),('DOWN',0),('BOTTOM',0)]),
    ("antiproton",      [('UP',1),('UP',1),('DOWN',1)]),
]
mesons = [  # name, (q1, q2) - same color (R bank)
    ("pi+ u dbar",      [('UP',0),('DOWN',1)]),
    ("pi- d ubar",      [('DOWN',0),('UP',1)]),
    ("K+ sbar u",       [('STRANGE',1),('UP',0)]),   # antiquark first: either order
    ("J/psi c cbar",    [('CHARM',0),('CHARM',1)]),
    ("B+ u bbar",       [('UP',0),('BOTTOM',1)]),
    ("D0 c ubar",       [('CHARM',0),('UP',1)]),
]
asm = ["""# AxISA v2.0 step 3 (see docs/ISA.md's "Quark flavor and hadrons"):
# BARYON QN / MESON QN build real hadrons from flavor codes and report
# their quantum numbers. GENERATED by tools/gen_hadrons_test.py - the
# expected values in tb/tb_hadrons.v come from that script's PDG quark
# table, not from the RTL. Each result is STOREd to 0x400+4k.
    ADDI N4, N0, 55          # sentinel - no illegal hadron may write it
"""]
checks = []
k = 0
def slot():
    global k; a = 0x400 + 4*k; k += 1; return a
for name, qs in baryons:
    a = slot(); w, f = qn(qs)
    asm.append(f"# {name}: Q={f[0]} B={f[1]} S={f[2]} C={f[3]} B'={f[4]} T={f[5]} 2*I3={f[6]}")
    for reg, (fl, anti) in zip(("R1", "G1", "B1"), qs):
        asm.append(f"    ADDI {reg}, {reg[0]}0, {tok(fl, anti)}")
    asm.append("    BARYON QN, N1, R1, G1, B1")
    asm.append(f"    STORE N1, N0, 0x{a:X}")
    checks.append((a, w, name))
for name, qs in mesons:
    a = slot(); w, f = qn(qs)
    asm.append(f"# {name}: Q={f[0]} B={f[1]} S={f[2]} C={f[3]} B'={f[4]} T={f[5]} 2*I3={f[6]}")
    for reg, (fl, anti) in zip(("R2", "R3"), qs):
        asm.append(f"    ADDI {reg}, R0, {tok(fl, anti)}")
    asm.append("    MESON QN, N1, R2, R3")
    asm.append(f"    STORE N1, N0, 0x{a:X}")
    checks.append((a, w, name))
end = slot()
asm.append(f"    STORE N0, N0, 0x{end:X}      # end marker slot stays 0")
checks.append((end, 0, "end-marker slot stays 0"))
sys.path.insert(0, 'sw')
from asm_test1 import meson, R, G
illegal = [
    ("BARYON QN, r = 7 (no 7th flavor)",            ["ADDI R1, R0, 7", "ADDI G1, G0, UP", "ADDI B1, B0, UP"], "BARYON QN, N4, R1, G1, B1"),
    ("BARYON QN, g = 0 (not a quark)",              ["ADDI R1, R0, UP", "ADDI G1, G0, 0"], "BARYON QN, N4, R1, G1, B1"),
    ("BARYON QN, b = -7",                           ["ADDI G1, G0, UP", "ADDI B1, B0, -7"], "BARYON QN, N4, R1, G1, B1"),
    ("BARYON QN, u u ubar (quarks + antiquark)",    ["ADDI B1, B0, -UP"], "BARYON QN, N4, R1, G1, B1"),
    ("MESON QN, u d (two quarks)",                  ["ADDI R2, R0, UP", "ADDI R3, R0, DOWN"], "MESON QN, N4, R2, R3"),
    ("MESON QN, ubar dbar (two antiquarks)",        ["ADDI R2, R0, -UP", "ADDI R3, R0, -DOWN"], "MESON QN, N4, R2, R3"),
    ("BARYON QN, t u d (top never hadronizes)",     ["ADDI R1, R0, TOP", "ADDI G1, G0, UP", "ADDI B1, B0, DOWN"], "BARYON QN, N4, R1, G1, B1"),
    ("MESON QN, t tbar (top never hadronizes)",     ["ADDI R2, R0, TOP", "ADDI R3, R0, -TOP"], "MESON QN, N4, R2, R3"),
    ("MESON QN, red u + green dbar (color octet)",  ["ADDI R2, R0, UP", "ADDI G2, G0, -DOWN"], f".word 0x{meson(2, 4, R, 2, G, 2):08X}"),
]
for name, setup, instr in illegal:
    asm.append(f"# illegal: {name}")
    asm += ["    " + x for x in setup] + ["    " + instr]
asm.append(f"    HALT N7                  # tohost = traps taken (expect {len(illegal)})")
asm.append("""
.org 0x200
handler:
    MFCAUSE N3
    ADD N6, N6, N3           # n6 = sum of causes (expect 0 = all ILLEGAL)
    ADDI N7, N7, 1           # n7 = trap count
    MFEPC N5
    ADDI N5, N5, 4           # skip the bad instruction
    MTEPC N5
    RFT
""")
open('sw/hadrons_test.axasm', 'w', encoding='utf-8').write("\n".join(asm))

tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.0 step 3 (see sw/hadrons_test.axasm and docs/ISA.md's
// "Quark flavor and hadrons"): BARYON QN / MESON QN on 8 baryons and 6
// mesons plus 7 illegal combinations. GENERATED by
// tools/gen_hadrons_test.py - expected words come from its PDG table.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/hadrons_test.hex').replace('module tb_gluon;', 'module tb_hadrons;')
tb = tb.replace('max_cycles = 200;', 'max_cycles = 600;')
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
lines = [f"            check(tohost_value, 32'd{len(illegal)}, \"tohost (n7 = traps taken)\");",
         "            check(dut.n_bank.regs[6], 32'd0, \"n6 (sum of trap causes, 0 = ILLEGAL)\");",
         "            check(dut.n_bank.regs[4], 32'd55, \"n4 (sentinel: no illegal hadron wrote)\");"]
for addr, w, name in checks:
    lines.append(f"            check(dut.dmem.mem[11'h{addr >> 2:03X}], 32'h{w:08X}, \"{name}\");")
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA HADRONS TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA HADRONS TEST(S) FAILED')
open('tb/tb_hadrons.v', 'w', encoding='utf-8').write(tb)
print(f"{len(checks)} result checks, {len(illegal)} illegal cases")
for addr, w, name in checks: print(f"  0x{addr:X} {w:08X} {name}")
