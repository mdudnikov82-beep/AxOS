# Generates control_unit_stage (the decode register) at the end of
# rtl/control_unit.v, from control_unit's own port list - so the two can
# never drift apart. Re-run after any change to control_unit's ports or
# to what it decodes from instruction 0:
#     python tools/gen_decode_stage.py        (from hardware/axisa_core)
#
# Why the stage exists: on sky130 the core's worst path started at the
# squash register, masked the instruction, decoded it (about 14 ns of
# the 31 ns of logic at ss) and only then read registers, added the
# address and drove the bus / UART ports. control_unit is a function of
# the instruction bits alone, so it can run one cycle earlier, straight
# off the instruction memory's read port, and its outputs can be
# registered instead of the raw instruction. Same cycle count, same
# one-bubble redirect: the register holds exactly decode(instr) of what
# the old registered fetch + squash mask produced (see cpu_core.v).
#
# The register's reset / kill value is decode(0) - what the old design
# decoded during the warm-up and post-redirect bubble (instr masked to
# 0). It is a constant, found here by simulating control_unit with
# instr = 0 (iverilog), so the flip-flops get a constant async reset;
# a simulation-only check compares it with a live control_unit(0).
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CU = os.path.join(HERE, "..", "rtl", "control_unit.v")
MARK = "// ===== control_unit_stage: GENERATED by tools/gen_decode_stage.py - do not edit by hand ====="

src = open(CU, encoding="utf-8").read()
base = src.split(MARK)[0].rstrip() + "\n"
ports = []
in_ports = False
for line in base.splitlines():
    code = line.split("//")[0].strip()
    if re.match(r"module\s+control_unit\s*\(", code):
        in_ports = True
        continue
    if in_ports and code.startswith(");"):
        break
    mm = re.match(r"output\s+(?:reg|wire)\s*(?:\[(\d+):0\])?\s*(.*)$", code) if in_ports else None
    if mm:
        for n in mm.group(2).rstrip(",").split(","):
            ports.append((n.strip(), int(mm.group(1) or 0) + 1))
    elif in_ports and code.startswith("output"):
        sys.exit("cannot parse: " + line)
if not ports:
    sys.exit("no outputs found in control_unit")

# decode(0), by simulation
iv = os.environ.get("IVERILOG_DIR", r"C:\iverilog\bin" if os.name == "nt" else "")
iverilog = os.path.join(iv, "iverilog") if iv else "iverilog"
vvp = os.path.join(iv, "vvp") if iv else "vvp"
with tempfile.TemporaryDirectory() as td:
    tb = os.path.join(td, "tb.v")
    with open(tb, "w") as f:
        f.write("module tb;\n")
        for n, w in ports:
            f.write(f"  wire [{w-1}:0] {n};\n")
        f.write("  control_unit u(.instr(32'b0), " + ", ".join(f".{n}({n})" for n, _ in ports) + ");\n")
        f.write("  initial begin #1;\n")
        for n, w in ports:
            f.write(f'    $display("{n} %b", {n});\n')
        f.write("  end\nendmodule\n")
    cu_only = os.path.join(td, "cu.v")
    open(cu_only, "w", encoding="utf-8").write(base)
    out = os.path.join(td, "a.vvp")
    subprocess.run([iverilog, "-o", out, cu_only, tb], check=True)
    res = subprocess.run([vvp, "-n", out], check=True, capture_output=True, text=True).stdout
zero = dict(l.split() for l in res.splitlines() if l.strip() and not l.startswith("VCD"))
for n, w in ports:
    if n not in zero or len(zero[n]) != w or set(zero[n]) - set("01"):
        sys.exit(f"decode(0) of {n} is not a clean constant: {zero.get(n)}")

total = sum(w for _, w in ports)
L = [MARK, "//",
     f"// {len(ports)} control_unit outputs, {total} bits. REGISTERED=1: control_unit",
     "// decodes `instr` (the instruction memory's combinational read of the",
     "// next pc) and the outputs are registered - updated when `en`",
     "// (!cpu_stall), forced to decode(0) by `kill` (the next cycle is a",
     "// squash bubble) and by reset. REGISTERED=0: the old structure,",
     "// control_unit on (squash ? 0 : instr) with `instr` already registered",
     "// by the instruction memory (SYNC_READ=1 - for FPGA block RAM).",
     "module control_unit_stage #(parameter REGISTERED = 1) (",
     "    input  wire        clk, reset, en, kill, squash,",
     "    input  wire [31:0] instr,"]
L += [f"    output wire [{w-1}:0] {n}{',' if i < len(ports) - 1 else ''}" for i, (n, w) in enumerate(ports)]
L += [");"]
L += ["    generate if (REGISTERED) begin: g_reg"]
for n, w in ports:
    L.append(f"        wire [{w-1}:0] d_{n};")
    L.append(f"        reg  [{w-1}:0] q_{n};")
L.append("        control_unit u (.instr(instr), " + ", ".join(f".{n}(d_{n})" for n, _ in ports) + ");")
L.append("        always @(posedge clk or posedge reset) begin")
L.append("            if (reset) begin")
for n, w in ports:
    L.append(f"                q_{n} <= {w}'b{zero[n]};")
L.append("            end else if (en) begin")
L.append("                if (kill) begin")
for n, w in ports:
    L.append(f"                    q_{n} <= {w}'b{zero[n]};")
L.append("                end else begin")
for n, w in ports:
    L.append(f"                    q_{n} <= d_{n};")
L.append("                end")
L.append("            end")
L.append("        end")
for n, w in ports:
    L.append(f"        assign {n} = q_{n};")
L.append("`ifndef SYNTHESIS")
L.append("`ifndef VERILATOR")
L.append("        // the constants above must still be decode(0) - simulation only:")
L.append("        // OpenLane lints with Verilator, which rejects the #delay below")
for n, w in ports:
    L.append(f"        wire [{w-1}:0] z_{n};")
L.append("        control_unit z (.instr(32'b0), " + ", ".join(f".{n}(z_{n})" for n, _ in ports) + ");")
L.append("        initial begin #0.001;")
L.append("            if ({" + ", ".join(f"z_{n}" for n, _ in ports) + "} !== {" +
         ", ".join(f"{w}'b{zero[n]}" for n, w in ports) + "}) begin")
L.append('                $display("FATAL: control_unit_stage is stale - re-run tools/gen_decode_stage.py");')
L.append("                $finish;")
L.append("            end")
L.append("        end")
L.append("`endif")
L.append("`endif")
L.append("    end else begin: g_comb")
L.append("        control_unit u (.instr(squash ? 32'b0 : instr), " + ", ".join(f".{n}({n})" for n, _ in ports) + ");")
L.append("    end endgenerate")
L.append("endmodule")
open(CU, "w", encoding="utf-8", newline="\n").write(base + "\n" + "\n".join(L) + "\n")
print(f"control_unit_stage: {len(ports)} outputs, {total} bits")
