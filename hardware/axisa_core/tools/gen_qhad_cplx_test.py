# Generates sw/qhad_cplx_test.axasm + tb/tb_qhad_cplx.v (v2.2). Run from
# hardware/axisa_core.
#
# sw/qhad_test.axasm only mixes |00> (every Im is 0, beta = 0), so a QHAD
# that loses one of its four writes can still pass it. Here both
# amplitudes are complex and nonzero, all four results are checked bit for
# bit against a binary32 model of the documented order
#   alpha' = fl(fl(alpha + beta) * k),  beta' = fl(fl(alpha - beta) * k),
# per component, k = fl(1/sqrt 2) = 0x3F3504F3 - and the instruction right
# after QHAD reads two of its results (its terminal-cycle write included),
# so the CPU must not run ahead of the sequencer.
import struct


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


K = struct.unpack('<f', struct.pack('<I', 0x3F3504F3))[0]
ALPHA = (f32(0.75), f32(-1.25))      # r0, r1
BETA = (f32(0.3), f32(2.0))          # r2, r3
new_alpha = tuple(f32(f32(a + b) * K) for a, b in zip(ALPHA, BETA))
new_beta = tuple(f32(f32(a - b) * K) for a, b in zip(ALPHA, BETA))
r = [new_alpha[0], new_alpha[1], new_beta[0], new_beta[1]]
r5 = (bits(r[3]) + bits(r[0])) & 0xFFFFFFFF


def load32(reg, v):
    # R/G/B have no zero register: clear reg itself first
    return [f"XOR {reg}, {reg}, {reg}", f"ADDI {reg}, {reg}, {v >> 21}", f"SLLI {reg}, {reg}, 11", f"ORI {reg}, {reg}, {(v >> 10) & 0x7FF}",
            f"SLLI {reg}, {reg}, 10", f"ORI {reg}, {reg}, {v & 0x3FF}"]


asm = ["""# AxISA v2.2: QHAD on complex amplitudes. GENERATED by
# tools/gen_qhad_cplx_test.py - expected bits in tb/tb_qhad_cplx.v come
# from its binary32 model. alpha = (r0, r1), beta = (r2, r3)."""]
for i, v in enumerate([ALPHA[0], ALPHA[1], BETA[0], BETA[1]]):
    asm += ["    " + x for x in load32(f"R{i}", bits(v))]
asm += ["    QHAD 0, 0",
        "    ADD R5, R3, R0          # right after QHAD: reads beta' Im (its LAST write) and alpha' Re",
        "    HALT N0", ""]
open('sw/qhad_cplx_test.axasm', 'w', encoding='utf-8').write("\n".join(asm))

tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.2 (see sw/qhad_cplx_test.axasm): QHAD on complex amplitudes,
// all four writes bit-exact, and the next instruction sees them.
// GENERATED by tools/gen_qhad_cplx_test.py.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/qhad_cplx_test.hex').replace('module tb_gluon;', 'module tb_qhad_cplx;')
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
names = ["alpha' Re", "alpha' Im", "beta' Re", "beta' Im"]
lines = [f"            check(dut.r_bank.regs[{i}], 32'h{bits(v):08X}, \"r{i} {n} ({v:+.6g})\");" for i, (v, n) in enumerate(zip(r, names))]
lines.append(f"            check(dut.r_bank.regs[5], 32'h{r5:08X}, \"r5 = r3 + r0, read right after QHAD\");")
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA QHAD-CPLX TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA QHAD-CPLX TEST(S) FAILED')
open('tb/tb_qhad_cplx.v', 'w', encoding='utf-8').write(tb)
print("alpha'", new_alpha, "beta'", new_beta)
