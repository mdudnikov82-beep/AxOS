# Generates sw/sweep_test.axasm + tb/tb_sweep.v for AxISA v2.3 step 3
# (SWEEP: the average plaquette of a whole periodic L x L lattice). Run
# from hardware/axisa_core.
#
# Lattice layout (docs/ISA.md): link U_mu(x, y) at base + 72*(2*(y*L + x) + mu).
# Expected words come from a binary32 model of the documented order - PLAQ's
# order, site by site (x fastest), one trace carried across all sites, then
# fl(tr * fl(1/(3 L^2))). float64 checks the physics: <P> agrees, and is
# unchanged by a gauge transformation of the whole lattice.
import contextlib
import io
import random
import sys

sys.path.insert(0, 'sw')
sys.path.insert(0, 'tools')
with contextlib.redirect_stdout(io.StringIO()):
    from gen_plaq_test import su3, matmul, dag, r32, bits, term, f32  # noqa: E402


def links_of(lat, L, x, y):
    """U1 = U_0(x,y), U2 = U_1(x+1,y), U3 = U_0(x,y+1), U4 = U_1(x,y)."""
    return lat[(x, y, 0)], lat[((x + 1) % L, y, 1)], lat[(x, (y + 1) % L, 0)], lat[(x, y, 1)]


def ref_sweep(lat, L):
    tr = 0.0
    for y in range(L):
        for x in range(L):
            u1, u2, u3, u4 = links_of(lat, L, x, y)
            for k in range(3):
                v = [(u4[k][j].real, -u4[k][j].imag) for j in range(3)]
                for elem in (lambda i, j: (u3[j][i].real, -u3[j][i].imag), lambda i, j: (u2[i][j].real, u2[i][j].imag)):
                    w = []
                    for i in range(3):
                        ar = ai = 0.0
                        for j in range(3):
                            t_re, t_im = term(*elem(i, j), *v[j])
                            ar, ai = f32(ar + t_re), f32(ai + t_im)
                        w.append((ar, ai))
                    v = w
                for j in range(3):
                    t_re, _ = term(u1[k][j].real, u1[k][j].imag, *v[j])
                    tr = f32(tr + t_re)
    return f32(tr * f32(1 / (3 * L * L)))


def avg64(lat, L):
    s = 0.0
    for y in range(L):
        for x in range(L):
            u1, u2, u3, u4 = links_of(lat, L, x, y)
            m = matmul(matmul(matmul(u1, u2), dag(u3)), dag(u4))
            s += (m[0][0] + m[1][1] + m[2][2]).real / 3
    return s / (L * L)


random.seed(31)


def rnd_su3(scale):
    return su3(*[(k, random.uniform(-scale, scale)) for k in (1, 2, 3, 4, 5, 6, 7, 8)])


def lattice(L, scale):
    return {(x, y, mu): rnd_su3(scale) for y in range(L) for x in range(L) for mu in (0, 1)}


IDENT = su3()
LATS = [   # base, L, links (float64), note
    (0x400, 4, lattice(4, 2.0), "a hot 4x4 lattice"),
    (0x100, 2, lattice(2, 0.15), "a warm 2x2 lattice"),
    (0xD00, 1, {(0, 0, 0): IDENT, (0, 0, 1): IDENT}, "a cold 1x1 lattice: <P> = 1 exactly"),
]

# gauge invariance of the whole 4x4 lattice, float64:
# U_mu(x) -> g(x) U_mu(x) g(x + mu)^dag
L4, lat4 = LATS[0][1], LATS[0][2]
g = {(x, y): rnd_su3(3.0) for y in range(L4) for x in range(L4)}
gauged = {(x, y, mu): matmul(matmul(g[(x, y)], u), dag(g[((x + (mu == 0)) % L4, (y + (mu == 1)) % L4)]))
          for (x, y, mu), u in lat4.items()}
assert abs(avg64(lat4, L4) - avg64(gauged, L4)) < 1e-12, "gauge invariance"

results = []
for base, L, lat, note in LATS:
    l32 = {k: r32(u) for k, u in lat.items()}
    p = ref_sweep(l32, L)
    assert abs(p - avg64(lat, L)) < 1e-5, (note, p, avg64(lat, L))
    results.append(p)
    print(f"0x{base:03X} L={L}: <P> = {p:+.7f} (0x{bits(p):08X})  float64 {avg64(lat, L):+.9f}  {note}")
assert results[2] == 1.0

OUT = 0x3E0
asm = [f"""# AxISA v2.3 step 3 (see docs/ISA.md's SWEEP section): the average
# plaquette of a whole periodic L x L lattice in ONE instruction.
# GENERATED by tools/gen_sweep_test.py - expected bits in tb/tb_sweep.v
# come from its binary32 model. <P> values are STOREd from 0x{OUT:X}."""]
for i, (base, L, lat, note) in enumerate(LATS):
    asm.append(f"# {note}")
    asm.append(f"    ADDI N1, N0, 0x{base:X}")
    if i == 1:
        asm += [f"    SWEEP N1, N1, {L}            # nd == ns", f"    STORE N1, N0, 0x{OUT + 4 * i:X}"]
    else:
        asm += [f"    SWEEP N2, N1, {L}", f"    STORE N2, N0, 0x{OUT + 4 * i:X}"]
asm.append("""# illegal: misaligned, and a 4x4 lattice (2304 bytes) that would run into the UART window
    ADDI N1, N0, 0x402
    SWEEP N2, N1, 2
    ADDI N1, N0, 0x800
    SWEEP N2, N1, 4
# user mode: SWEEP reads physical memory, so it is kernel-only
    ADDI N1, N0, 0
    MTSMODE N1               # saved_mode = user
    ADDI N1, N0, user_code
    MTEPC N1
    RFT
user_code:
    ADDI N1, N0, 0x100
    SWEEP N2, N1, 2          # must trap: privilege violation (CAUSE 3)
    HALT N7                  # tohost = traps taken (expect 3)

.org 0x200
handler:
    MFCAUSE N5
    ADD N6, N6, N5           # n6 = sum of causes (expect 0+0+3 = 3)
    ADDI N7, N7, 1           # n7 = trap count
    MFEPC N5
    ADDI N5, N5, 4           # skip the trapping instruction
    MTEPC N5
    RFT
""")
text = "\n".join(asm)
words = 0
for line in text.splitlines():
    code = line.split('#', 1)[0].strip()
    if code.startswith('user_code:'):
        break
    if code and not code.endswith(':'):
        words += 1
text = text.replace("ADDI N1, N0, user_code", f"ADDI N1, N0, 0x{4 * words:X}   # = user_code")
open('sw/sweep_test.axasm', 'w', encoding='utf-8').write(text)

tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.3 step 3 (see sw/sweep_test.axasm and docs/ISA.md's SWEEP
// section): bit-exact average plaquettes of whole 4x4, 2x2 and 1x1
// periodic lattices, nd == ns, 3 traps, and the cycle count.
// GENERATED by tools/gen_sweep_test.py.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/sweep_test.hex').replace('module tb_gluon;', 'module tb_sweep;')
tb = tb.replace('max_cycles = 200;', 'max_cycles = 30000;')
preload = []
for base, L, lat, _ in LATS:
    for (x, y, mu), u in lat.items():
        u = r32(u)
        b = base + 72 * (2 * (y * L + x) + mu)
        for i in range(3):
            for j in range(3):
                w = b // 4 + 2 * (3 * i + j)
                preload += [f"        dut.dmem.mem[{w}] = 32'h{bits(u[i][j].real):08X};",
                            f"        dut.dmem.mem[{w + 1}] = 32'h{bits(u[i][j].imag):08X};"]
tb = tb.replace("    always #5 clk = ~clk;", """    always #5 clk = ~clk;

    // cycles each SWEEP keeps is_sweep high (the trapping ones count 1)
    integer lat [0:15];
    integer n_lat, cur;
    initial begin n_lat = 0; cur = 0; end
    always @(posedge clk) begin
        if (!reset && dut.is_sweep) cur = cur + 1;
        else if (cur != 0) begin
            if (n_lat < 16) lat[n_lat] = cur;
            n_lat = n_lat + 1;
            cur = 0;
        end
    end""")
tb = tb.replace("        reset = 0;\n", "        // the lattices\n" + "\n".join(preload) + "\n        reset = 0;\n", 1)
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
lines = ["            check(tohost_value, 32'd3, \"tohost (n7 = traps taken)\");",
         "            check(dut.n_bank.regs[6], 32'd3, \"n6 (causes 0+0+3: 2 ILLEGAL, 1 PRIV)\");"]
for i, ((base, L, _, note), p) in enumerate(zip(LATS, results)):
    lines.append(f"            check(dut.dmem.mem[{(OUT + 4 * i) // 4}], 32'h{bits(p):08X}, \"<P> of the {L}x{L} lattice ({p:+.6f})\");")
lines.append(f"            check(n_lat, {len(LATS) + 3}, \"SWEEP instructions seen\");")
PER_SITE = 336   # pipelined PLAQ per site; a single site (= PLAQ) is 13 + 336 = 349
for k, (_, L, _, _) in enumerate(LATS):
    lines.append(f"            check(lat[{k}], {13 + PER_SITE * L * L}, \"cycles of SWEEP L={L}\");")
for k in range(3):
    lines.append(f"            check(lat[{len(LATS) + k}], 1, \"cycles of trapping SWEEP #{k}\");")
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA SWEEP TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA SWEEP TEST(S) FAILED')
open('tb/tb_sweep.v', 'w', encoding='utf-8').write(tb)
