# Generates sw/hop_test_c{0..3}.axasm + tb/tb_hop.v for AxISA v2.3 step 4
# (HOP, nearest-neighbour links). Run from hardware/axisa_core.
#
# Four cores on a 2 x 2 torus (core id = 2y + x; every core has a +x, -x,
# +y and -y neighbour, wrapping around like QCDOC's torus). Each core:
#   1. SENDs a word in every direction, then RECVs one from every
#      direction (the one-word mailboxes make "everyone sends first" safe);
#   2. core 0 sends three more words +y; core 2 dawdles before taking them,
#      so core 0's second SEND must wait - order and values must survive;
#   3. exchanges an SU(3) link with its x neighbour (SENDL / RECVL, 18
#      words; x = 0 sends first, x = 1 receives first) and multiplies it
#      with its own link (LINKMUL) - a halo exchange, then use.
import contextlib
import io
import sys

sys.path.insert(0, 'sw')
sys.path.insert(0, 'tools')
with contextlib.redirect_stdout(io.StringIO()):
    from gen_plaq_test import su3, r32, bits  # noqa: E402
    from gen_linkmul_test import ref_linkmul  # noqa: E402

DIRS = ['+X', '-X', '+Y', '-Y']


def coord(c):
    return c % 2, c // 2


def nb(c, d):
    x, y = coord(c)
    if d in (0, 1):
        x ^= 1
    else:
        y ^= 1
    return 2 * y + x


def word(c, d):
    return 0x100 + 16 * c + d


LINKS = [r32(su3((1, 0.3 + c), (5, -0.7 * c), (8, 0.2 + 0.1 * c))) for c in range(4)]
EXTRA = [0xA1, 0xA2, 0xA3]
TRAPS = """# 5. traps: a misaligned link, one running into the UART window, user mode
    ADDI N1, N0, 0x402
    HOP SENDL +X, N1
    ADDI N1, N0, 0xFBC
    HOP RECVL -X, N1
    ADDI N1, N0, 0
    MTSMODE N1               # saved_mode = user
    ADDI N1, N0, user_code
    MTEPC N1
    RFT
user_code:
    ADDI N1, N0, 0x400
    HOP SENDL +X, N1         # must trap: privilege violation (CAUSE 3)
    HALT N7                  # tohost = traps taken (expect 3)

.org 0x200
handler:
    MFCAUSE N5
    ADD N6, N6, N5           # n6 = sum of causes (expect 0+0+3 = 3)
    ADDI N7, N7, 1           # n7 = trap count
    MFEPC N5
    ADDI N5, N5, 4           # skip the trapping instruction
    MTEPC N5
    RFT"""

expect = {c: {} for c in range(4)}      # core -> {addr: value}
for c in range(4):
    for d in range(4):
        # mailbox d holds what my d-neighbour sent in direction d^1
        expect[c][0x300 + 4 * d] = word(nb(c, d), d ^ 1)
for i, v in enumerate(EXTRA):
    expect[2][0x310 + 4 * i] = v
expect[1][0x320] = 0x5A5          # phase 4: core 3 -> core 1, late
for c in range(4):
    got = LINKS[nb(c, 0)]
    prod = ref_linkmul(LINKS[c], got, 0, 0)
    for i in range(3):
        for j in range(3):
            for base, m in ((0x480, got), (0x500, prod)):
                w = base + 8 * (3 * i + j)
                expect[c][w], expect[c][w + 4] = bits(m[i][j].real), bits(m[i][j].imag)

for c in range(4):
    x, y = coord(c)
    a = [f"""# AxISA v2.3 step 4: core {c} = (x {x}, y {y}) of a 2x2 torus. GENERATED by
# tools/gen_hop_test.py (see it for the plan); tb/tb_hop.v checks memory.
# 1. a word in every direction, then one from every direction"""]
    for d in range(4):
        a += [f"    ADDI N1, N0, 0x{word(c, d):X}", f"    HOP SEND {DIRS[d]}, N1"]
    for d in range(4):
        a += [f"    HOP RECV N2, {DIRS[d]}", f"    STORE N2, N0, 0x{0x300 + 4 * d:X}"]
    a.append("# 2. back-pressure")
    if c == 0:
        for v in EXTRA:
            a += [f"    ADDI N1, N0, 0x{v:X}", "    HOP SEND +Y, N1     # the 2nd and 3rd wait for core 2"]
    if c == 2:
        a += ["    ADDI N3, N0, 60", "dawdle:", "    ADDI N3, N3, -1", "    BNE N3, N0, dawdle"]
        for i in range(3):
            a += ["    HOP RECV N2, -Y", f"    STORE N2, N0, 0x{0x310 + 4 * i:X}"]
    a.append("# 3. swap SU(3) links with the x neighbour, then multiply them")
    a += ["    ADDI N1, N0, 0x400", "    ADDI N3, N0, 0x480"]
    swap = ["    HOP SENDL +X, N1", "    HOP RECVL -X, N3"]
    a += swap if x == 0 else swap[::-1]
    a += ["    ADDI N4, N0, 0x500", "    LINKMUL N4, N1, N3   # own link x the neighbour's"]
    a.append("# 4. a RECV that really has to wait: core 3 sends late")
    if c == 3:
        a += ["    ADDI N3, N0, 80", "late:", "    ADDI N3, N3, -1", "    BNE N3, N0, late",
              "    ADDI N1, N0, 0x5A5", "    HOP SEND -Y, N1      # into core 1's +y mailbox"]
    if c == 1:
        a += ["    HOP RECV N2, +Y      # waits for core 3", "    STORE N2, N0, 0x320"]
        a += [TRAPS]
    else:
        a += ["    HALT N0"]
    a.append("")
    text = "\n".join(a)
    if c == 1:
        words = 0
        for line in text.splitlines():
            code = line.split('#', 1)[0].strip()
            if code.startswith('user_code:'):
                break
            if code and not code.endswith(':'):
                words += 1
        assert 4 * words < 0x200
        text = text.replace("ADDI N1, N0, user_code", f"ADDI N1, N0, 0x{4 * words:X}   # = user_code")
    open(f'sw/hop_test_c{c}.axasm', 'w', encoding='utf-8').write(text)

L = []
w = L.append
w("""// AxISA v2.3 step 4 (see tools/gen_hop_test.py): HOP on a 2x2 torus of four
// cores - words in all four directions, back-pressure on a full mailbox,
// and an SU(3) link exchange used by LINKMUL. GENERATED by gen_hop_test.py.
`timescale 1ns/1ps

module tb_hop;
    reg clk, reset;
    integer errors, cycle_count;
    always #5 clk = ~clk;
""")
for c in range(4):
    w(f"    wire        halted{c};\n    wire [31:0] tohost{c};")
    w(f"    wire [3:0]  ov{c}, or{c}, iv{c}, ir{c};\n    wire [31:0] od{c};\n    wire [127:0] id{c};")
for c in range(4):
    for d in range(4):
        n = nb(c, d)
        # my link d is my neighbour n's link d^1
        w(f"    assign iv{c}[{d}] = ov{n}[{d ^ 1}];  assign id{c}[{32 * d + 31}:{32 * d}] = od{n};  assign or{c}[{d}] = ir{n}[{d ^ 1}];")
for c in range(4):
    w(f"""
    cpu_core #(.INSTR_MEM_WORDS(1024), .INSTR_INIT_FILE("sw/hop_test_c{c}.hex")) core{c} (
        .clk(clk), .reset(reset), .halted(halted{c}), .tohost_value(tohost{c}), .irq_in(1'b0),
        .bus_req(), .bus_addr(), .bus_write_data(), .bus_mem_write(), .bus_mem_size(), .bus_mem_unsigned(),
        .bus_grant(1'b0), .bus_read_data(32'b0),
        .uart_tx_valid(), .uart_tx_data(), .uart_rx_data_in(8'b0), .uart_rx_ready_in(1'b0), .uart_rx_ack(),
        .hop_out_valid(ov{c}), .hop_out_data(od{c}), .hop_out_ready(or{c}),
        .hop_in_valid(iv{c}), .hop_in_data(id{c}), .hop_in_ready(ir{c})
    );""")
w("""
    // cycles core 0 spent in a SEND whose +y mailbox (core 2's) was full
    integer bp;
    initial bp = 0;
    always @(posedge clk) if (!reset && core0.hop_send && !core0.hop_out_ready[2]) bp = bp + 1;
    // cycles core 1 spent in a RECV whose +y mailbox was still empty
    integer rw;
    initial rw = 0;
    always @(posedge clk) if (!reset && core1.hop_recv && !core1.hop_mb_full[2]) rw = rw + 1;

    task check(input [31:0] got, input [31:0] expected, input [48*8-1:0] name);
        begin
            if (got !== expected) begin
                $display("FAIL: %0s got=0x%h expected=0x%h", name, got, expected);
                errors = errors + 1;
            end
        end
    endtask

    initial begin
        errors = 0; clk = 0; reset = 1; cycle_count = 0;
        @(posedge clk); @(posedge clk);""")
for c in range(4):
    for i in range(3):
        for j in range(3):
            m = LINKS[c]
            wd = 0x400 // 4 + 2 * (3 * i + j)
            w(f"        core{c}.dmem.mem[{wd}] = 32'h{bits(m[i][j].real):08X}; core{c}.dmem.mem[{wd + 1}] = 32'h{bits(m[i][j].imag):08X};")
w("""        reset = 0;
        while (!(halted0 && halted1 && halted2 && halted3) && cycle_count < 20000) begin
            @(posedge clk);
            cycle_count = cycle_count + 1;
        end
        if (!(halted0 && halted1 && halted2 && halted3)) begin
            $display("FAIL: not every core halted within 20000 cycles (deadlock?)");
            errors = errors + 1;
        end else
            $display("All four cores halted after %0d cycles", cycle_count);""")
n_checks = 0
for c in range(4):
    for addr, v in sorted(expect[c].items()):
        w(f"        check(core{c}.dmem.mem[{addr // 4}], 32'h{v:08X}, \"core {c} @0x{addr:03X}\");")
        n_checks += 1
w(f"""        if (bp < 50) begin
            $display("FAIL: core 0 waited only %0d cycles on core 2's full mailbox (expected back-pressure)", bp);
            errors = errors + 1;
        end else $display("PASS: core 0 waited %0d cycles on core 2's full mailbox", bp);
        if (rw < 50) begin
            $display("FAIL: core 1's RECV waited only %0d cycles for core 3", rw);
            errors = errors + 1;
        end else $display("PASS: core 1's RECV waited %0d cycles for core 3", rw);
        check(tohost1, 32'd3, "core 1 tohost (traps taken)");
        check(core1.n_bank.regs[6], 32'd3, "core 1 n6 (causes 0+0+3: 2 ILLEGAL, 1 PRIV)");
        if (errors == 0) $display("PASS: {n_checks} words across 4 cores");
        if (errors == 0) $display("ALL AXISA HOP TESTS PASSED");
        else $display("%0d AXISA HOP TEST(S) FAILED", errors);
        $finish;
    end
endmodule
""")
open('tb/tb_hop.v', 'w', encoding='utf-8').write("\n".join(L))
print(f"{n_checks} expected words")
