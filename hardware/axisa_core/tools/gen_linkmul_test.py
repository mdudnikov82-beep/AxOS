# Generates sw/linkmul_test.axasm + tb/tb_linkmul.v for AxISA v2.3 step 1
# (LINKMUL, C = A' B' for 3x3 complex matrices in memory). Run from
# hardware/axisa_core.
#
# The matrices are real SU(3) elements (gen_plaq_test.su3: checked unitary
# with det 1 in float64), rounded to binary32. Expected words come from a
# binary32 reference model of docs/ISA.md's exact order - NOT the RTL:
# column j of C = A' (column j of B'), each element accumulated from +0
# over k = 0, 1, 2 with SU3MUL's term rounding.
import io
import contextlib
import sys

sys.path.insert(0, 'sw')
sys.path.insert(0, 'tools')
with contextlib.redirect_stdout(io.StringIO()):
    from gen_plaq_test import su3, matmul, dag, r32, bits, term, f32  # noqa: E402



def prime(m, d):
    """A or A^dag as the hardware addresses it: element (i, k)."""
    return (lambda i, k: (m[k][i].real, -m[k][i].imag)) if d else (lambda i, k: (m[i][k].real, m[i][k].imag))


def ref_linkmul(a, b, da, db):
    ea, eb = prime(a, da), prime(b, db)
    c = [[0j] * 3 for _ in range(3)]
    for j in range(3):
        v = [eb(k, j) for k in range(3)]
        for i in range(3):
            acc_re = acc_im = 0.0
            for k in range(3):
                t_re, t_im = term(*ea(i, k), *v[k])
                acc_re, acc_im = f32(acc_re + t_re), f32(acc_im + t_im)
            c[i][j] = complex(acc_re, acc_im)
    return c


A = r32(su3((1, 0.7), (4, -0.4), (6, 1.1), (3, 0.3), (8, -0.9)))
B = r32(su3((2, 0.5), (5, 1.3), (7, -0.8), (8, 0.6)))
X = r32(su3((1, 0.05), (5, -0.08), (8, 0.03)))          # a Metropolis proposal: close to 1
LAST = 0x1000 - 72                                       # 0xFB8: highest legal base

mem = {0x400: A, 0x480: B, 0x500: X, LAST: B}           # program-visible matrices, by base
cases = []   # (dst, a, b, da, db, note)


def run(dst, a, b, da, db, note):
    mem[dst] = ref_linkmul(mem[a], mem[b], da, db)
    cases.append((dst, a, b, da, db, note))


run(0x600, 0x400, 0x480, 0, 0, "C = A B")
run(0x680, 0x400, 0x480, 1, 0, "C = A^dag B")
run(0x700, 0x400, 0x480, 0, 1, "C = A B^dag")
run(0x780, 0x400, 0x400, 1, 0, "C = A^dag A: unitarity, ~ identity")
run(0x800, 0x480, 0x400, 1, 1, "C = B^dag A^dag (= (A B)^dag)")
run(0x480, 0x500, 0x480, 0, 0, "in place, C == B: the Metropolis proposal U <- X U")
run(0x400, 0x400, 0x500, 0, 1, "in place, C == A: A <- A X^dag")
run(0x880, LAST, 0x400, 0, 0, "A at the highest legal base")

# physics sanity, float64: A^dag A = 1 and (AB)^dag = B^dag A^dag
idn = mem[0x780]
assert all(abs(idn[i][j] - (i == j)) < 1e-6 for i in range(3) for j in range(3))
ab = matmul(A, B)
assert all(abs(mem[0x800][i][j] - ab[j][i].conjugate()) < 1e-6 for i in range(3) for j in range(3))
assert all(abs(mem[0x600][i][j] - ab[i][j]) < 1e-6 for i in range(3) for j in range(3))

asm = ["""# AxISA v2.3 step 1 (see docs/ISA.md's LINKMUL section): C = A' B' for
# 3x3 complex matrices in memory. GENERATED by tools/gen_linkmul_test.py -
# the expected words in tb/tb_linkmul.v come from its binary32 model. The
# testbench preloads A at 0x400, B at 0x480 (and at 0xFB8), X at 0x500.
"""]
for dst, a, b, da, db, note in cases:
    asm += [f"# {note}", f"    ADDI N1, N0, 0x{a:X}", f"    ADDI N2, N0, 0x{b:X}", f"    ADDI N3, N0, 0x{dst:X}",
            f"    LINKMUL N3, N1{'^' if da else ''}, N2{'^' if db else ''}"]
asm += ["""# illegal: a misaligned A, a B and a C that would run into the UART window
    ADDI N1, N0, 0x402
    LINKMUL N3, N1, N2
    ADDI N1, N0, 0x400
    ADDI N2, N0, 0xFBC
    LINKMUL N3, N1, N2
    ADDI N2, N0, 0x480
    ADDI N3, N0, 0xFC0
    LINKMUL N3, N1, N2
# user mode: LINKMUL reads and writes physical memory, so it is kernel-only
    ADDI N1, N0, 0
    MTSMODE N1               # saved_mode = user
    ADDI N1, N0, user_code
    MTEPC N1
    RFT
user_code:
    ADDI N1, N0, 0x400
    ADDI N3, N0, 0x900
    LINKMUL N3, N1, N2       # must trap: privilege violation (CAUSE 3)
    HALT N7                  # tohost = traps taken (expect 4)

.org 0x200
handler:
    MFCAUSE N5
    ADD N6, N6, N5           # n6 = sum of causes (expect 0+0+0+3 = 3)
    ADDI N7, N7, 1           # n7 = trap count
    MFEPC N5
    ADDI N5, N5, 4           # skip the trapping instruction
    MTEPC N5
    RFT
"""]
text = "\n".join(asm)
words = 0
for line in text.splitlines():
    code = line.split('#', 1)[0].strip()
    if code.startswith('user_code:'):
        break
    if code and not code.endswith(':'):
        words += 1
assert 4 * words < 0x200
text = text.replace("ADDI N1, N0, user_code", f"ADDI N1, N0, 0x{4 * words:X}   # = user_code")
open('sw/linkmul_test.axasm', 'w', encoding='utf-8').write(text)

tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.3 step 1 (see sw/linkmul_test.axasm and docs/ISA.md's LINKMUL
// section): bit-exact C = A' B' with every dagger combination, in place on
// either side, the highest legal base, 4 traps, and the cycle count.
// GENERATED by tools/gen_linkmul_test.py.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/linkmul_test.hex').replace('module tb_gluon;', 'module tb_linkmul;')
tb = tb.replace('max_cycles = 200;', 'max_cycles = 8000;')
preload = []
for base, m in ((0x400, A), (0x480, B), (0x500, X), (LAST, B)):
    for i in range(3):
        for j in range(3):
            w = base // 4 + 2 * (3 * i + j)
            preload += [f"        dut.dmem.mem[{w}] = 32'h{bits(m[i][j].real):08X};",
                        f"        dut.dmem.mem[{w + 1}] = 32'h{bits(m[i][j].imag):08X};"]
tb = tb.replace("    always #5 clk = ~clk;", """    always #5 clk = ~clk;

    // cycles each LINKMUL keeps is_linkmul high (the trapping ones count 1)
    integer lat [0:15];
    integer n_lat, cur;
    initial begin n_lat = 0; cur = 0; end
    always @(posedge clk) begin
        if (!reset && dut.is_linkmul) cur = cur + 1;
        else if (cur != 0) begin
            if (n_lat < 16) lat[n_lat] = cur;
            n_lat = n_lat + 1;
            cur = 0;
        end
    end""")
tb = tb.replace("        reset = 0;\n", "        // the matrices\n" + "\n".join(preload) + "\n        reset = 0;\n", 1)
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
lines = ["            check(tohost_value, 32'd4, \"tohost (n7 = traps taken)\");",
         "            check(dut.n_bank.regs[6], 32'd3, \"n6 (causes 0+0+0+3: 3 ILLEGAL, 1 PRIV)\");"]
final = {}
for dst, *_ in cases:
    final[dst] = mem[dst]
for dst, m in sorted(final.items()):
    for i in range(3):
        for j in range(3):
            w = dst // 4 + 2 * (3 * i + j)
            lines.append(f"            check(dut.dmem.mem[{w}], 32'h{bits(m[i][j].real):08X}, \"C@{dst:03X}[{i}][{j}] Re\");")
            lines.append(f"            check(dut.dmem.mem[{w + 1}], 32'h{bits(m[i][j].imag):08X}, \"C@{dst:03X}[{i}][{j}] Im\");")
CYC = 1 + 3 * (9 + 9 * 14) + 18
lines.append(f"            check(n_lat, {len(cases) + 4}, \"LINKMUL instructions seen\");")
for k in range(len(cases)):
    lines.append(f"            check(lat[{k}], {CYC}, \"cycles of legal LINKMUL #{k}\");")
for k in range(4):
    lines.append(f"            check(lat[{len(cases) + k}], 1, \"cycles of trapping LINKMUL #{k}\");")
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA LINKMUL TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA LINKMUL TEST(S) FAILED')
open('tb/tb_linkmul.v', 'w', encoding='utf-8').write(tb)
print(f"{len(cases)} products, {CYC} cycles each; A^dag A diagonal:",
      " ".join(f"{idn[i][i].real:.7f}" for i in range(3)))
