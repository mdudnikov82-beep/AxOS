# Generates sw/reunit_test.axasm + tb/tb_reunit.v for AxISA v2.3 step 2
# (REUNIT). Run from hardware/axisa_core.
#
# The expected words come from running REUNIT's own microprogram
# (tools/reunit_ucode.py - the same list rtl/reunit_rom.v is generated
# from) on binary32 values, and LINKMUL's binary32 model for the drift
# loop. Independently of both, float64 checks that every result really is
# in SU(3): U U^dag = 1 and det U = 1.
import contextlib
import io
import math
import random
import struct
import sys

sys.path.insert(0, 'sw')
sys.path.insert(0, 'tools')
with contextlib.redirect_stdout(io.StringIO()):
    from gen_plaq_test import su3, r32, bits, f32  # noqa: E402
    from gen_linkmul_test import ref_linkmul  # noqa: E402
import reunit_ucode as U  # noqa: E402


def ref_reunit(m):
    s = [0.0] * U.N_SCRATCH
    for i in range(3):
        for j in range(3):
            s[U.re(i, j)], s[U.im(i, j)] = m[i][j].real, m[i][j].imag
    o = U.run(s, f32, lambda x: f32(math.sqrt(x)))
    return [[complex(o[U.re(i, j)], o[U.im(i, j)]) for j in range(3)] for i in range(3)]


def drift(m):
    """max |U U^dag - 1| and |det U - 1| in float64."""
    uu = max(abs(sum(m[i][k] * m[j][k].conjugate() for k in range(3)) - (i == j)) for i in range(3) for j in range(3))
    det = (m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1]) - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
           + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]))
    return uu, abs(det - 1)


random.seed(23)
U0 = su3((1, 0.7), (4, -0.4), (6, 1.1), (3, 0.3), (8, -0.9))
DRIFTED = r32([[z * (1 + random.uniform(-3e-3, 3e-3)) + complex(random.uniform(-2e-3, 2e-3), random.uniform(-2e-3, 2e-3))
                for z in row] for row in U0])
RANDOM = r32([[complex(random.uniform(-1, 1), random.uniform(-1, 1)) for _ in range(3)] for _ in range(3)])
LINK = r32(su3((2, 0.5), (5, 1.3), (7, -0.8), (8, 0.6)))
X = r32(su3((1, 0.05), (5, -0.08), (8, 0.03)))
LOOPS = 30
LAST = 0x1000 - 72

mem = {0x400: DRIFTED, 0x480: RANDOM, LAST: DRIFTED, 0x500: LINK, 0x580: X}
results = {}
report = []
for base, note in ((0x400, "a link that drifted off SU(3)"), (0x480, "a random, far-from-unitary matrix"),
                   (LAST, "the highest legal base")):
    before = drift(mem[base])
    results[base] = ref_reunit(mem[base])
    report.append((note, before, drift(results[base])))
u = LINK
for _ in range(LOOPS):
    u = ref_linkmul(X, u, 0, 0)
before = drift(u)
results[0x500] = ref_reunit(u)
report.append((f"the link after {LOOPS} x LINKMUL U <- X U", before, drift(results[0x500])))
for note, b, a in report:
    assert a[0] < 1e-6 and a[1] < 1e-6, (note, a)   # binary32: a few ulp
    print(f"{note:45s} |UU^-1| {b[0]:.1e} -> {a[0]:.1e}   |det-1| {b[1]:.1e} -> {a[1]:.1e}")

asm = [f"""# AxISA v2.3 step 2 (see docs/ISA.md's REUNIT section): pull matrices back
# onto SU(3). GENERATED by tools/gen_reunit_test.py - expected words in
# tb/tb_reunit.v come from REUNIT's own microprogram run on binary32 values.
# The testbench preloads a drifted link at 0x400 (and 0x{LAST:X}), a random
# matrix at 0x480, a link U at 0x500 and a near-1 X at 0x580.
    ADDI N1, N0, 0x400
    REUNIT N1
    ADDI N1, N0, 0x480
    REUNIT N1
    ADDI N1, N0, 0x{LAST:X}
    REUNIT N1
# {LOOPS} Metropolis-style products U <- X U drift U off SU(3); then REUNIT
    ADDI N1, N0, 0x580
    ADDI N2, N0, 0x500
    ADDI N4, N0, {LOOPS}
drift_loop:
    LINKMUL N2, N1, N2
    ADDI N4, N4, -1
    BNE N4, N0, drift_loop
    REUNIT N2
# illegal: misaligned, and running into the UART window
    ADDI N1, N0, 0x402
    REUNIT N1
    ADDI N1, N0, 0xFBC
    REUNIT N1
# user mode: REUNIT reads and writes physical memory, so it is kernel-only
    ADDI N1, N0, 0
    MTSMODE N1               # saved_mode = user
    ADDI N1, N0, user_code
    MTEPC N1
    RFT
user_code:
    ADDI N1, N0, 0x400
    REUNIT N1                # must trap: privilege violation (CAUSE 3)
    HALT N7                  # tohost = traps taken (expect 3)

.org 0x200
handler:
    MFCAUSE N5
    ADD N6, N6, N5           # n6 = sum of causes (expect 0+0+3 = 3)
    ADDI N7, N7, 1           # n7 = trap count
    MFEPC N5
    ADDI N5, N5, 4           # skip the trapping instruction
    MTEPC N5
    RFT
"""]
text = "\n".join(asm)
words = 0
for line in text.splitlines():
    code = line.split('#', 1)[0].strip()
    if code.startswith('user_code:'):
        break
    if code and not code.endswith(':'):
        words += 1
text = text.replace("ADDI N1, N0, user_code", f"ADDI N1, N0, 0x{4 * words:X}   # = user_code")
open('sw/reunit_test.axasm', 'w', encoding='utf-8').write(text)

tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.3 step 2 (see sw/reunit_test.axasm and docs/ISA.md's REUNIT
// section): matrices pulled back onto SU(3), bit-exact against REUNIT's
// own microprogram; a link drifted by 30 LINKMULs; 3 traps; equal timing.
// GENERATED by tools/gen_reunit_test.py.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/reunit_test.hex').replace('module tb_gluon;', 'module tb_reunit;')
tb = tb.replace('max_cycles = 200;', 'max_cycles = 40000;')
preload = []
for base, m in mem.items():
    for i in range(3):
        for j in range(3):
            w = base // 4 + 2 * (3 * i + j)
            preload += [f"        dut.dmem.mem[{w}] = 32'h{bits(m[i][j].real):08X};",
                        f"        dut.dmem.mem[{w + 1}] = 32'h{bits(m[i][j].imag):08X};"]
tb = tb.replace("    always #5 clk = ~clk;", """    always #5 clk = ~clk;

    // cycles each REUNIT keeps is_reunit high (the trapping ones count 1)
    integer lat [0:15];
    integer n_lat, cur;
    initial begin n_lat = 0; cur = 0; end
    always @(posedge clk) begin
        if (!reset && dut.is_reunit) cur = cur + 1;
        else if (cur != 0) begin
            if (n_lat < 16) lat[n_lat] = cur;
            n_lat = n_lat + 1;
            cur = 0;
        end
    end""")
tb = tb.replace("        reset = 0;\n", "        // the matrices\n" + "\n".join(preload) + "\n        reset = 0;\n", 1)
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
lines = ["            check(tohost_value, 32'd3, \"tohost (n7 = traps taken)\");",
         "            check(dut.n_bank.regs[6], 32'd3, \"n6 (causes 0+0+3: 2 ILLEGAL, 1 PRIV)\");"]
for base, m in sorted(results.items()):
    for i in range(3):
        for j in range(3):
            w = base // 4 + 2 * (3 * i + j)
            lines.append(f"            check(dut.dmem.mem[{w}], 32'h{bits(m[i][j].real):08X}, \"@{base:03X}[{i}][{j}] Re\");")
            lines.append(f"            check(dut.dmem.mem[{w + 1}], 32'h{bits(m[i][j].imag):08X}, \"@{base:03X}[{i}][{j}] Im\");")
lines.append("            check(n_lat, 7, \"REUNIT instructions seen\");")
# decode + 19 loads + 2 per add/sub/mul micro-op + 4 sqrt/div (~40 each) + END + 18 stores
lines.append("            check(lat[0], 443, \"cycles of REUNIT #0\");")
for k in (1, 2, 3):
    lines.append(f"            check(lat[{k}], lat[0], \"REUNIT #{k} takes as long as #0 (data-independent)\");")
for k in (4, 5, 6):
    lines.append(f"            check(lat[{k}], 1, \"cycles of trapping REUNIT #{k - 4}\");")
lines.append("            $display(\"REUNIT takes %0d cycles\", lat[0]);")
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA REUNIT TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA REUNIT TEST(S) FAILED')
open('tb/tb_reunit.v', 'w', encoding='utf-8').write(tb)
