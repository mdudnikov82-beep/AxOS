# Generates sw/regge_test.axasm + tb/tb_regge.v for AxISA v2.1 step 3
# (REGGE, string theory / Regge trajectories). Run from hardware/axisa_core.
#
# Two independent checks:
#  - bits: every result word must equal a binary32 reference model that
#    follows docs/ISA.md's exact operation order (rounding each op of a
#    binary32 computation through a Python double is exact: double has
#    >= 2*24+2 bits, so double rounding is innocuous for +, *, sqrt);
#  - physics: the predicted spins of real hadrons (PDG masses) must land
#    on their real spins - checked here, before any RTL runs.
import math
import struct
import sys

sys.path.insert(0, 'sw')
from asm_test1 import regge


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


ALPHA = f32(0.9)
INV_ALPHA = f32(1 / 0.9)
A0 = {'M': f32(0.5), 'B': f32(0.15)}
assert bits(ALPHA) == 0x3F666666 and bits(INV_ALPHA) == 0x3F8E38E4
assert bits(A0['M']) == 0x3F000000 and bits(A0['B']) == 0x3E19999A


def spin(kind, m):
    return f32(A0[kind] + f32(ALPHA * f32(m * m)))


def mass(kind, j):
    x = f32(f32(j - A0[kind]) * INV_ALPHA)
    return float('nan') if x < 0 else f32(math.sqrt(x))


def word(x):
    return 0x7FC00000 if math.isnan(x) else bits(x)


# (kind, op, input, note, real value it must reproduce, tolerance)
cases = [
    ('M', 'SPIN', 0.775,  "rho(770)    -> J = 1",     1.0, 0.1),
    ('M', 'SPIN', 1.3183, "a2(1320)    -> J = 2",     2.0, 0.1),
    ('M', 'SPIN', 1.6888, "rho3(1690)  -> J = 3",     3.0, 0.1),
    ('M', 'SPIN', 1.967,  "a4(1970)    -> J = 4",     4.0, 0.1),
    ('B', 'SPIN', 1.232,  "Delta(1232) -> J = 3/2",   1.5, 0.1),
    ('B', 'SPIN', 1.930,  "Delta(1950) -> J = 7/2",   3.5, 0.1),
    ('B', 'SPIN', 2.420,  "Delta(2420) -> J = 11/2",  5.5, 0.1),
    ('M', 'MASS', 1.0,    "J = 1 meson -> rho mass",  0.775, 0.04),
    ('M', 'MASS', 5.0,    "J = 5 meson -> rho5(2350)", 2.33, 0.11),
    ('B', 'MASS', 1.5,    "J = 3/2 baryon -> Delta(1232)", 1.232, 0.01),
    ('M', 'MASS', 0.0,    "J = 0 is below the intercept: no real mass (NaN)", None, None),
]

asm = ["""# AxISA v2.1 step 3 (see docs/ISA.md's REGGE section): string theory's
# origin - hadrons on straight Regge trajectories, J = a0 + a' M^2, as a
# rotating relativistic string predicts. GENERATED by
# tools/gen_regge_test.py: the expected bits in tb/tb_regge.v come from
# its binary32 reference model, and that script checks the physics
# (real PDG hadron spins/masses) before writing anything.
"""]
checks = []


def load32(reg, v):
    return [f"ADDI {reg}, N0, {v >> 21}", f"SLLI {reg}, {reg}, 11", f"ORI {reg}, {reg}, {(v >> 10) & 0x7FF}",
            f"SLLI {reg}, {reg}, 10", f"ORI {reg}, {reg}, {v & 0x3FF}"]


for k, (kind, op, x, note, real, tol) in enumerate(cases):
    x = f32(x)
    y = spin(kind, x) if op == 'SPIN' else mass(kind, x)
    if real is None:
        assert math.isnan(y)
    else:
        assert abs(y - real) <= tol, (note, y, real)       # the physics holds
    addr = 0x400 + 4 * k
    asm.append(f"# {note}: {x:g} -> {y:.4f}")
    asm += ["    " + i for i in load32("N1", bits(x))]
    asm.append(f"    REGGE {op}.{kind}, N2, N1")
    asm.append(f"    STORE N2, N0, 0x{addr:X}")
    checks.append((addr, word(y), note))
# nd == ns: the operand is latched on the first cycle
x = f32(1.6888)
asm.append("# nd == ns (in place)")
asm += ["    " + i for i in load32("N3", bits(x))]
asm.append("    REGGE SPIN.M, N3, N3")
asm.append("    HALT N3                  # tohost = J of rho3(1690)")
tohost = bits(spin('M', x))
open('sw/regge_test.axasm', 'w', encoding='utf-8').write("\n".join(asm) + "\n")

n_spin = sum(1 for c in cases if c[1] == 'SPIN') + 1
n_mass = sum(1 for c in cases if c[1] == 'MASS')
tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.1 step 3 (see sw/regge_test.axasm and docs/ISA.md's REGGE
// section): bit-exact SPIN/MASS on real hadrons, NaN below the
// intercept, in-place operation, and per-instruction cycle counts.
// GENERATED by tools/gen_regge_test.py.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/regge_test.hex').replace('module tb_gluon;', 'module tb_regge;')
tb = tb.replace('max_cycles = 200;', 'max_cycles = 3000;')
tb = tb.replace('input [48*8-1:0] name', 'input [64*8-1:0] name')
tb = tb.replace("    always #5 clk = ~clk;", """    always #5 clk = ~clk;

    // cycles each REGGE keeps is_regge high, split by kind
    integer cur, n_spin, n_mass, spin_cyc, mass_cyc, spin_bad, mass_bad;
    reg cur_mass;
    initial begin cur = 0; n_spin = 0; n_mass = 0; spin_cyc = -1; mass_cyc = -1; spin_bad = 0; mass_bad = 0; end
    always @(posedge clk) begin
        if (!reset && dut.is_regge) begin cur = cur + 1; cur_mass = dut.regge_funct[1]; end
        else if (cur != 0) begin
            if (cur_mass) begin
                n_mass = n_mass + 1;
                if (mass_cyc == -1) mass_cyc = cur; else if (cur != mass_cyc) mass_bad = mass_bad + 1;
            end else begin
                n_spin = n_spin + 1;
                if (spin_cyc == -1) spin_cyc = cur; else if (cur != spin_cyc) spin_bad = spin_bad + 1;
            end
            cur = 0;
        end
    end""")
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
lines = [f"            check(tohost_value, 32'h{tohost:08X}, \"tohost: SPIN.M in place (nd == ns)\");"]
for addr, w, note in checks:
    lines.append(f"            check(dut.dmem.mem[11'h{addr >> 2:03X}], 32'h{w:08X}, \"{note}\");")
lines += [f"            check(n_spin, {n_spin}, \"SPIN instructions timed\");",
          f"            check(n_mass, {n_mass}, \"MASS instructions timed\");",
          "            check(spin_cyc, 6, \"SPIN takes 6 cycles\");",
          "            check(spin_bad + mass_bad, 0, \"every SPIN / every MASS takes the same time\");",
          "            check(mass_cyc > spin_cyc, 1, \"MASS (with the sqrt) is slower than SPIN\");"]
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA REGGE TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA REGGE TEST(S) FAILED')
open('tb/tb_regge.v', 'w', encoding='utf-8').write(tb)
for addr, w, note in checks:
    print(f"  {w:08X}  {note}")
