# Generates sw/string_test.axasm + tb/tb_string.v for AxISA v2.0 step 4
# (STRING, asymptotic freedom). Expected results AND cycle counts come
# from the reference model below, written from docs/ISA.md - not from
# the RTL. Run from hardware/axisa_core.
import sys
sys.path.insert(0, 'sw')
from asm_test1 import string, N, R

def ref(a, b):
    d = abs(a - b)                         # positions as signed integers
    assert d < 2**32
    extra = min(d.bit_length(), 16)        # string breaks at d >= 2^16
    return d, 1 + extra

def load(reg, v):
    """Instructions that put the signed 32-bit value v into reg."""
    bank0 = reg[0] + "0"
    if -16384 <= v <= 16383:
        return [f"ADDI {reg}, {bank0}, {v}"]
    if v == 0x7FFFFFFF:
        return [f"ADDI {reg}, {bank0}, -1", f"SRLI {reg}, {reg}, 1"]
    if v > 0 and (v + 1) & v == 0:         # 2^k - 1
        return [f"ADDI {reg}, {bank0}, 1", f"SLLI {reg}, {reg}, {(v + 1).bit_length() - 1}", f"ADDI {reg}, {reg}, -1"]
    if v == -2**31:
        return [f"ADDI {reg}, {bank0}, 1", f"SLLI {reg}, {reg}, 31"]
    hi, lo = v >> 16, v & 0xFFFF
    assert 0 <= hi <= 16383 and lo < 16384, v
    out = [f"ADDI {reg}, {bank0}, {hi}", f"SLLI {reg}, {reg}, 16"]
    if lo:
        out.append(f"ORI {reg}, {reg}, {lo}")
    return out

cases = [  # bank, a, b, note
    ("R", 5, 5, "same place: no string"),
    ("R", 7, 6, "d=1"),
    ("G", 3, 8, "d=5, reversed order"),
    ("B", 1000, 0, "d=1000"),
    ("R", 0, 0x7FFF, "d=0x7FFF, 15 bits"),
    ("R", 0, 0xFFFF, "d=0xFFFF, longest unbroken string"),
    ("R", 0x10000, 0, "d=2^16: first break, 1 pair"),
    ("G", 0x30005, 0, "3 pairs + a 5-long segment"),
    ("B", -100, 150, "negative position"),
    ("R", 0x7FFFFFFF, -2**31, "d=2^32-1, the widest"),
]
asm = ["""# AxISA v2.0 step 4 (see docs/ISA.md's STRING section): asymptotic
# freedom. GENERATED by tools/gen_string_test.py - the expected results
# and cycle counts in tb/tb_string.v come from that script's reference
# model, not from the RTL. Each STRING is followed by a STORE so the
# testbench can time every STRING separately (it counts the cycles
# is_string stays high).
    ADDI N4, N0, 55          # sentinel - the illegal STRING may not write it
"""]
checks, lats = [], []
for k, (bank, a, b, note) in enumerate(cases):
    d, cyc = ref(a, b)
    addr = 0x400 + 4 * k
    asm.append(f"# {note}: d={d:#x}, {cyc} cycles")
    asm += ["    " + x for x in load(bank + "1", a) + load(bank + "2", b)]
    asm.append(f"    STRING N1, {bank}1, {bank}2")
    asm.append(f"    STORE N1, N0, 0x{addr:X}")
    checks.append((addr, d, note))
    lats.append((cyc, note))
end = 0x400 + 4 * len(cases)
asm.append(f"    STORE N0, N0, 0x{end:X}      # end marker slot stays 0")
checks.append((end, 0, "end-marker slot stays 0"))
asm.append(f"    .word 0x{string(4, N, 1, 2):08X}         # STRING N4, N1, N2 - N is colorless, no string")
lats.append((1, "illegal STRING on N traps at once"))
asm.append("    HALT N7                  # tohost = traps taken (expect 1)")
asm.append("""
.org 0x200
handler:
    MFCAUSE N3
    ADD N6, N6, N3           # n6 = sum of causes (expect 0 = ILLEGAL)
    ADDI N7, N7, 1           # n7 = trap count
    MFEPC N5
    ADDI N5, N5, 4           # skip the bad instruction
    MTEPC N5
    RFT
""")
open('sw/string_test.axasm', 'w', encoding='utf-8').write("\n".join(asm))

tb = open('tb/tb_gluon.v', encoding='utf-8').read()
tb = """// AxISA v2.0 step 4 (see sw/string_test.axasm and docs/ISA.md's STRING
// section): STRING results AND per-instruction cycle counts, plus the
// illegal N-bank case. GENERATED by tools/gen_string_test.py.
`timescale 1ns/1ps
""" + tb[tb.index('`ifndef INSTR_HEX'):]
tb = tb.replace('sw/gluon_test.hex', 'sw/string_test.hex').replace('module tb_gluon;', 'module tb_string;')
tb = tb.replace('max_cycles = 200;', 'max_cycles = 1000;')
# latency monitor: length of every run of consecutive is_string cycles
tb = tb.replace("    always #5 clk = ~clk;", f"""    always #5 clk = ~clk;

    integer lat [0:{len(lats) - 1}];
    integer n_lat, cur;
    initial begin n_lat = 0; cur = 0; end
    always @(posedge clk) begin
        if (!reset && dut.is_string) cur = cur + 1;
        else if (cur != 0) begin
            if (n_lat < {len(lats)}) lat[n_lat] = cur;
            n_lat = n_lat + 1;
            cur = 0;
        end
    end""")
a = tb.index("            check(tohost_value, 32'd2"); b = tb.index('        end\n\n        if (errors == 0)')
lines = ["            check(tohost_value, 32'd1, \"tohost (n7 = traps taken)\");",
         "            check(dut.n_bank.regs[6], 32'd0, \"n6 (trap cause, 0 = ILLEGAL)\");",
         "            check(dut.n_bank.regs[4], 32'd55, \"n4 (sentinel: illegal STRING wrote nothing)\");"]
for addr, d, note in checks:
    lines.append(f"            check(dut.dmem.mem[11'h{addr >> 2:03X}], 32'h{d:08X}, \"result: {note}\");")
lines.append(f"            check(n_lat, {len(lats)}, \"number of STRING instructions timed\");")
for i, (cyc, note) in enumerate(lats):
    lines.append(f"            check(lat[{i}], {cyc}, \"cycles: {note}\");")
tb = tb[:a] + "\n".join(lines) + "\n" + tb[b:]
tb = tb.replace('input [48*8-1:0] name', 'input [64*8-1:0] name')
tb = tb.replace('ALL AXISA GLUON TESTS PASSED', 'ALL AXISA STRING TESTS PASSED').replace('AXISA GLUON TEST(S) FAILED', 'AXISA STRING TEST(S) FAILED')
open('tb/tb_string.v', 'w', encoding='utf-8').write(tb)
for (addr, d, note), (cyc, _) in zip(checks, lats):
    print(f"  {d:#010x} {cyc:2d} cycles  {note}")
