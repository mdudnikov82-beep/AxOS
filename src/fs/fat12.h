#ifndef FAT12_H
#define FAT12_H

// Загружает FAT12-том (LBA 0-511 на build/disk.img, 256 КБ) через IDE в RAM
// по адресу 0x20000. Возвращает 1 при успехе, 0 если диск не найден или
// не содержит валидный FAT12-том - в этом случае остальные функции этого
// модуля ничего не делают (возвращают 0).
int fat12_init();

// Выводит список файлов корневой директории FAT12-раздела
void fat12_list();

// Печатает содержимое файла (имя в формате "name.ext", регистр не важен)
// Возвращает 1, если файл найден, 0 - если нет
int fat12_cat(char* filename);

// Загружает файл filename (имя в формате "name.ext", регистр не важен)
// в buffer (макс. max_size байт). Возвращает размер файла в байтах,
// или 0, если файл не найден.
unsigned int fat12_load(char* filename, unsigned char* buffer, unsigned int max_size);

// Удаляет файл filename (помечает запись 0xE5, освобождает кластеры).
// Возвращает 1 при успехе, 0 если файл не найден или диск заблокирован.
int fat12_delete(char* filename);

// Создаёт или перезаписывает файл filename (имя в формате "name.ext")
// содержимым data (size байт). Возвращает 1 при успехе, 0 если диск
// заблокирован (см. fat12_set_locked) или корневая директория/место
// на диске заняты.
int fat12_write(char* filename, unsigned char* data, unsigned int size);

// Включает (1) или отключает (0) защиту FAT12-диска от записи.
// По умолчанию диск заблокирован (fat12_write всегда возвращает 0).
void fat12_set_locked(int locked);

// Возвращает 1, если диск заблокирован от записи, иначе 0.
int fat12_is_locked();

// Возвращает 1, если fat12_init() успешно загрузил том, иначе 0.
int fat12_is_ready();

// Перечисление файлов и директорий корневой директории по индексу.
// index=0,1,2,... — 0-based позиция среди действительных записей.
// Возвращает 1 и заполняет name_out (макс. 13 байт "NAME.EXT\0"), *size_out,
// *is_dir_out (1=директория, 0=файл), или 0 если записей больше нет.
int fat12_readdir(unsigned int index, char* name_out, unsigned int* size_out, int* is_dir_out);

// Создаёт директорию dirname в корневой директории FAT12-раздела.
// Возвращает 1 при успехе, 0 если диск не готов/заблокирован,
// FAT12_MKDIR_EXISTS если имя уже занято, FAT12_MKDIR_NOSPACE если нет
// свободной записи в корне или свободного кластера.
#define FAT12_MKDIR_EXISTS  -1
#define FAT12_MKDIR_NOSPACE -2
int fat12_mkdir(char* dirname);

#endif
