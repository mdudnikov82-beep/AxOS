[bits 32]
global _start
extern _kernel_main
extern __bss_start
extern __bss_end

_start:
    mov esp, 0x90000    ; <--- ВОТ ЭТА СТРОКА РЕШИТ ВСЁ

    ; boot.asm грузит с диска только фиксированный бюджет секторов кода
    ; ядра - .bss (неинициализированные globals/static) в этот бюджет не
    ; входит и физически никогда не читается с диска. До сих пор она
    ; "случайно" читалась как нули (QEMU обнуляет RAM при старте), но
    ; любой рост .bss за пределы того, что грузит boot.asm, оставляет
    ; "хвост" с мусором из физической памяти - например, ide_lock (ide.c)
    ; мог стартовать НЕ нулём и spin_lock() в ide_read_sector() зависал
    ; навсегда на первом же секторе. Обнуляем явно, как и положено.
    ;
    ; ИСТОРИЧЕСКАЯ ЗАМЕТКА: раньше здесь было предупреждение, что GDT
    ; живёт на 0x7c00-0x7e00 и .bss нельзя дорастить до этого адреса -
    ; в прошлом это реально валило систему в #GP -> тройной сбой (см.
    ; "Буфер обмена" в README.md). С тех пор boot.asm сам себя копирует
    ; на 0x0600 перед чтением ядра с диска (нужно было увеличить число
    ; читаемых секторов - буфер чтения иначе заезжал в свой же
    ; работающий код на 0x7c00) - GDT теперь физически живёт на 0x0600,
    ; а 0x7c00 свободна. Тем не менее: общий принцип "не плодить крупные
    ; static-буферы в .bss бездумно, проверяй __bss_end (nm build/kernel.exe)
    ; после изменений" остаётся правильной практикой сам по себе.
    mov edi, __bss_start
    mov ecx, __bss_end
    sub ecx, edi
    xor eax, eax
    rep stosb

    call _kernel_main   ; Вызываем наше Си-ядро
    jmp $               ; Если Си-ядро вдруг завершится — зависаем тут