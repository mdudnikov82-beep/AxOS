#ifndef SPINLOCK_H
#define SPINLOCK_H

// =================================================================
//  Spinlock - примитив синхронизации для ОДНОГО CPU
// =================================================================
//
// На многоядерной машине spinlock защищает от ДРУГОГО ЯДРА, читающего
// тот же lock "прямо сейчас". У нас одно ядро - конкурентного доступа
// в этом смысле не бывает. Опасность тут другая: ПЕРЕКЛЮЧЕНИЕ ЗАДАЧ
// (preemption). Если задача A держит общий ресурс (например, IDE-
// контроллер - см. ide.c) и её прерывает таймерный тик, schedule()
// может запустить задачу B, которая полезет в тот же ресурс, пока A
// его не отпустила. lock здесь именно от ЭТОГО, а не от "настоящего"
// параллелизма.
//
// spin_lock() устроен так:
//   1. cli - выключает прерывания на момент проверки-и-установки флага
//      (без этого таймерный тик между "проверили - свободен" и
//      "поставили - занят" мог бы переключить на другую задачу ровно
//      в этом окне, и обе посчитали бы лок своим).
//   2. Если свободен - ставим флаг и восстанавливаем IF, КАКИМ он был
//      ДО cli (а не безусловно включаем) - если вызывающий код сам уже
//      шёл с IF=0 (например, внутри обработчика int 0x80 - см.
//      комментарий у IDT[0x80] в kernel.c), успешный захват без
//      конкуренции не должен тихо включать ему прерывания как побочный
//      эффект.
//   3. Если занят - восстанавливаем IF и ждём hlt. На одном CPU это
//      единственный способ дать держателю лока дойти до unlock: hlt
//      останавливает нас до следующего прерывания (как минимум
//      таймерного тика), после которого планировщик может выбрать
//      ЕГО задачу и дать ей закончить работу. Тот же приём, что в
//      ide_wait_irq()/sleep_ms() (kernel.c/ide.c).
typedef volatile int spinlock_t;

static inline int spin_save_and_disable_irq(void) {
    unsigned int eflags;
    __asm__ volatile("pushf\n\tpop %0\n\tcli" : "=r"(eflags));
    return (eflags & 0x200) != 0; // бит IF
}

static inline void spin_restore_irq(int was_enabled) {
    if (was_enabled) __asm__ volatile("sti");
}

static inline void spin_lock(spinlock_t* lock) {
    while (1) {
        int was_enabled = spin_save_and_disable_irq();
        if (!*lock) {
            *lock = 1;
            spin_restore_irq(was_enabled);
            return;
        }
        spin_restore_irq(was_enabled);
        __asm__ volatile("sti\n\thlt");
    }
}

// Снять lock - обычная запись, никаких манипуляций с прерываниями не
// нужно: на одном CPU выровненная запись int атомарна сама по себе.
static inline void spin_unlock(spinlock_t* lock) {
    *lock = 0;
}

#endif
