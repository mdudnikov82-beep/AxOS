; Вся логика выбора функции теперь живёт в C (syscall_dispatch +
; таблица syscall_table в kernel.c). Этот файл — лишь тонкий "мост":
; сохраняет регистры вызывающей программы, передаёт код функции (AH)
; и аргумент (ESI) в диспетчер и восстанавливает регистры обратно.
; При переносе на другую архитектуру (ARM) меняется только этот
; мост, а таблица вызовов и сама логика остаются прежними.

[bits 32]

extern _syscall_dispatch ; void syscall_dispatch(unsigned char func, char* arg) из kernel.c

global syscall_handler
global _syscall_handler ; GCC на Windows добавляет подчёркивание к C-функциям

_syscall_handler:
syscall_handler:
    pusha                ; Сохраняем все регистры вызвавшей программы, чтобы не сломать её работу

    movzx ecx, ah        ; Код функции (AH) -> ecx
    push esi             ; Аргумент (например, указатель на строку)
    push ecx             ; Код функции
    call _syscall_dispatch
    add esp, 8           ; cdecl: сами убираем аргументы со стека

    popa                 ; Восстанавливаем регистры
    iret                 ; Возвращаемся в программу, которая нас вызвала
