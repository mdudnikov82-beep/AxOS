#ifndef HEAP_H
#define HEAP_H

// Простой kmalloc/kfree поверх области 0x30000-0x90000 (384 КБ),
// которая свободна между концом FAT12-образа и стеком ядра.
// Алгоритм: связный список блоков с заголовком (размер, флаг free,
// указатель на следующий), поиск first-fit, разбиение блока при
// избытке места и слияние соседних свободных блоков при free().

// Инициализирует кучу: создаёт один свободный блок на весь регион.
// Вызывается один раз при старте ядра, после init_paging().
void init_heap();

// Выделяет блок памяти размером не менее size байт (4-байтное
// выравнивание). Возвращает NULL, если подходящего блока нет.
void* malloc(unsigned int size);

// Освобождает блок, выделенный malloc(), и сливает его с соседними
// свободными блоками (если есть).
void free(void* ptr);

#endif
