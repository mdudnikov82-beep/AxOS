[bits 32]
; Функция вывода строки в защищенном режиме
; Входящие параметры: EBX = адрес начала строки
print_string_pm:
    pusha                   ; Сохраняем все регистры
    mov edx, 0xB8000        ; Указатель на видеопамять

.loop:
    mov al, [ebx]           ; Берем символ из строки
    mov ah, 0x1F            ; Атрибут цвета (белый на синем)

    cmp al, 0               ; Проверка на конец строки (нулевой байт)
    je .done

    mov [edx], ax           ; Записываем символ и цвет в видеопамять
    add ebx, 1              ; Переходим к следующему символу строки
    add edx, 2              ; Переходим к следующей ячейке видеопамяти
    jmp .loop

.done:
    popa                    ; Восстанавливаем регистры
    ret