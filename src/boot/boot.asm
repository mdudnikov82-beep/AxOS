[org 0x7c00]

start:
    ; 1. Инициализация сегментов (Реальный режим)
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x9000          ; Настраиваем стек

    ; 2. Очистка экрана и настройка видеорежима (80x25 текст)
    mov ah, 0x00
    mov al, 0x03
    int 0x10

    ; --- Загружаем ядро Си с диска в память по адресу 0x1000 ---
    ; На дискете 18 секторов на трек. Сектор 1 трека 0/головки 0 занят
    ; загрузчиком, поэтому там остаются только секторы 2-18 (17 секторов).
    ; Оставшуюся часть ядра читаем с трека 0/головки 1 (секторы 1-18).

    ; Часть 1: цил.0, голова 0, секторы 2-18 (17 секторов = 8704 байт) -> 0x1000
    mov bx, 0x1000
    mov ah, 0x02
    mov al, 17
    mov ch, 0
    mov dh, 0
    mov cl, 2
    int 0x13
    jc disk_error
    cmp al, 17
    jne disk_error

    ; Часть 2: цил.0, голова 1, секторы 1-18 (18 секторов = 9216 байт) -> 0x1000 + 8704
    mov bx, 0x1000 + 17 * 512
    mov ah, 0x02
    mov al, 18
    mov ch, 0
    mov dh, 1
    mov cl, 1
    int 0x13
    jc disk_error
    cmp al, 18
    jne disk_error

    ; --- Загружаем FAT12-раздел (128 секторов = 64 КБ, начиная с цил.1/головы0/сектора1)
    ; в RAM по адресу 0x20000. Там лежат конфиги/скрипты, которые читает kernel (fat12.c). ---
    call load_fat12

    jmp disk_done

disk_error:
    ; Ошибка чтения диска: печатаем 'E' и останавливаемся
    mov ah, 0x0E
    mov al, 'E'
    int 0x10
    jmp $

disk_done:
    ; 3. Переход в 32-битный Защищенный Режим
    call switch_to_pm
    jmp $

; --- Загрузка FAT12-раздела с диска в RAM (0x2000:0x0000 = физ. адрес 0x20000) ---
; Раздел занимает 128 секторов (7 полных треков по 18 секторов + 2 сектора),
; читаем его трек за треком по таблице (цилиндр, головка, кол-во секторов).
load_fat12:
    mov ax, 0x2000
    mov es, ax
    xor bx, bx
    mov si, fat12_table
.fat12_loop:
    mov ch, [si]        ; цилиндр
    mov dh, [si+1]      ; головка
    mov al, [si+2]      ; количество секторов
    mov cl, 1           ; стартовый сектор (всегда начало трека)
    mov ah, 0x02
    mov [fat12_tmp], al
    int 0x13
    jc disk_error

    mov al, [fat12_tmp]
    xor ah, ah
    shl ax, 9           ; ax = количество секторов * 512
    add bx, ax

    add si, 3
    dec byte [fat12_count]
    jnz .fat12_loop

    xor ax, ax
    mov es, ax          ; восстанавливаем ES = 0
    ret

fat12_table: db 1,0,18, 1,1,18, 2,0,18, 2,1,18, 3,0,18, 3,1,18, 4,0,18, 4,1,2
fat12_count: db 8
fat12_tmp:   db 0

; --- Подключаем файлы конфигурации ---
%include "src/kernel/gdt.asm"
%include "src/boot/switch_to_pm.asm"
%include "src/lib/string.asm"

[bits 32]
BEGIN_PM:
    ; --- НАСТРОЙКА СТЕКА ДЛЯ 32-БИТНОГО РЕЖИМА ---
    mov ax, 0x10            ; 0x10 — это смещение сегмента данных в твоем GDT
    mov ds, ax
    mov ss, ax              ; Настраиваем сегмент стека
    mov es, ax
    mov fs, ax
    mov gs, ax
    
    mov esp, 0x90000        ; Выделяем стек подальше в памяти (0x90000), чтобы он не затер код
    mov ebp, esp            ; Базовый указатель стека
    ; -----------------------------------------------

    ; Теперь спокойно прыгаем по адресу 0x1000, где лежит наше Си-ядро
    ; --- ОТЛАДОЧНЫЙ ВЫВОД: Выводим 'L' перед переходом к ядру ---
    mov byte [0xb8000], 'L'      ; Выводим символ 'L' в левый верхний угол
    mov byte [0xb8001], 0x0F     ; Атрибут: белый текст на чёрном фоне
    ; --------------------------------------------------------------

    jmp 0x1000
    jmp $
    
; --- Сигнатура загрузочного сектора ---
times 510 - ($ - $$) db 0  
dw 0xAA55