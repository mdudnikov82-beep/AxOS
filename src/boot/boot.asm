[org 0x7c00]

; Самоперемещение на 0x0600: при увеличении читаемых секторов (было
; 53 = 27136 байт, стало 89 = 45568 байт - см. ниже) буфер чтения ядра
; доходит до 0xC200 и на пути проезжает через 0x7c00-0x7e00 - адрес, по
; которому BIOS положил САМ загрузчик и откуда мы прямо сейчас
; выполняемся. Входящие с диска данные переписывают код, который ещё
; не доисполнился - результат: BIOS молча зависает без кода ошибки (не
; jc, не "E" из disk_error - тихий hang прямо в середине int 0x13).
; Подтверждено отладкой: при 53 секторах буфер чтения кончался ровно на
; 0x7a00, чуть раньше опасной зоны - чисто повезло, а не было
; рассчитано. Классическое решение бутлоадеров: скопировать себя (все
; 512 байт сектора) в безопасный адрес ниже (0x0600) и продолжить
; оттуда - так 0x7c00-0x7e00 становится свободной памятью.
;
; NASM не разрешает второй [org] в одном файле (-f bin), а второй файл
; для релоцированной части означал бы переделывать build.bat - вместо
; этого считаем адреса вручную через RELOC_DELTA. Это не нужно почти
; везде: jc/jne/jmp на метки и call в 16-битном режиме кодируются
; относительным смещением (position-independent, копия работает с
; них без изменений). Поправка нужна только двум по-настоящему
; абсолютным местам: указателю на GDT (gdt_descriptor: dd gdt_start -
; CPU использует это как реальный адрес в памяти для lgdt) и far jump
; в защищённый режим (jmp CODE_SEG:init_pm - far jump всегда абсолютный,
; не относительный) - оба поправлены прямо в gdt.asm/switch_to_pm.asm
; через RELOC_DELTA, определённый здесь.
; %define, не equ - gdt.asm/switch_to_pm.asm проверяют его через %ifndef
; (тоже препроцессорная, не ассемблерная, конструкция) у себя, чтобы
; безопасно работать и без релокации (см. там) - %ifndef не видит equ.
%define RELOC_DELTA (0x0600 - 0x7c00)

start:
    ; 1. Инициализация сегментов (Реальный режим)
    cli
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7c00          ; временный стек ниже своего же кода - только на время копирования

    mov si, 0x7c00
    mov di, 0x0600
    mov cx, 512
    cld
    rep movsb

    jmp relocated_start + RELOC_DELTA

relocated_start:
    ; Выше конца буфера чтения ядра (0x1000 + 89*512 = 0xC200) - просто
    ; на всякий случай, чтобы стек точно не пересекался с буфером,
    ; даже не будучи единственной причиной зависания (см. выше).
    mov sp, 0xF000          ; Настраиваем стек

    ; 2. Очистка экрана и настройка видеорежима (80x25 текст)
    mov ah, 0x00
    mov al, 0x03
    int 0x10

    ; --- Загружаем ядро Си с диска в память по адресу 0x1000 ---
    ; На дискете 18 секторов на трек. Сектор 1 трека 0/головки 0 занят
    ; загрузчиком, поэтому там остаются только секторы 2-18 (17 секторов).
    ; Остальное ядро читаем с трека 0/головки 1 (секторы 1-18), трека
    ; 1/головки 0 (секторы 1-18), трека 1/головки 1 (секторы 1-18) и
    ; трека 2/головки 0 (секторы 1-18). Итого 17+18+18+18+18=89 секторов
    ; = 45568 байт - столько максимум может занимать kernel.bin (было
    ; 53 сектора = 27136 байт - не хватило с ростом ядра, см. CI).

    ; Часть 1: цил.0, голова 0, секторы 2-18 (17 секторов = 8704 байт) -> 0x1000
    mov bx, 0x1000
    mov ah, 0x02
    mov al, 17
    mov ch, 0
    mov dh, 0
    mov cl, 2
    int 0x13
    jc disk_error
    cmp al, 17
    jne disk_error

    ; Часть 2: цил.0, голова 1, секторы 1-18 (18 секторов = 9216 байт) -> 0x1000 + 8704
    mov bx, 0x1000 + 17 * 512
    mov ah, 0x02
    mov al, 18
    mov ch, 0
    mov dh, 1
    mov cl, 1
    int 0x13
    jc disk_error
    cmp al, 18
    jne disk_error

    ; Часть 3: цил.1, голова 0, секторы 1-18 (18 секторов = 9216 байт) -> 0x1000 + 17920
    mov bx, 0x1000 + 35 * 512
    mov ah, 0x02
    mov al, 18
    mov ch, 1
    mov dh, 0
    mov cl, 1
    int 0x13
    jc disk_error
    cmp al, 18
    jne disk_error

    ; Часть 4: цил.1, голова 1, секторы 1-18 (18 секторов = 9216 байт) -> 0x1000 + 27136
    mov bx, 0x1000 + 53 * 512
    mov ah, 0x02
    mov al, 18
    mov ch, 1
    mov dh, 1
    mov cl, 1
    int 0x13
    jc disk_error
    cmp al, 18
    jne disk_error

    ; Часть 5: цил.2, голова 0, секторы 1-18 (18 секторов = 9216 байт) -> 0x1000 + 36352
    mov bx, 0x1000 + 71 * 512
    mov ah, 0x02
    mov al, 18
    mov ch, 2
    mov dh, 0
    mov cl, 1
    int 0x13
    jc disk_error
    cmp al, 18
    jne disk_error

    jmp disk_done

disk_error:
    ; Ошибка чтения диска: печатаем 'E' и останавливаемся
    mov ah, 0x0E
    mov al, 'E'
    int 0x10
    jmp $

disk_done:
    ; 3. Переход в 32-битный Защищенный Режим
    call switch_to_pm
    jmp $

; --- Подключаем файлы конфигурации ---
%include "src/kernel/gdt.asm"
%include "src/boot/switch_to_pm.asm"
%include "src/lib/string.asm"

[bits 32]
BEGIN_PM:
    ; --- НАСТРОЙКА СТЕКА ДЛЯ 32-БИТНОГО РЕЖИМА ---
    mov ax, 0x10            ; 0x10 — это смещение сегмента данных в твоем GDT
    mov ds, ax
    mov ss, ax              ; Настраиваем сегмент стека
    mov es, ax
    mov fs, ax
    mov gs, ax
    
    mov esp, 0x90000        ; Выделяем стек подальше в памяти (0x90000), чтобы он не затер код
    mov ebp, esp            ; Базовый указатель стека
    ; -----------------------------------------------

    ; Теперь спокойно прыгаем по адресу 0x1000, где лежит наше Си-ядро
    ; --- ОТЛАДОЧНЫЙ ВЫВОД: Выводим 'L' перед переходом к ядру ---
    mov byte [0xb8000], 'L'      ; Выводим символ 'L' в левый верхний угол
    mov byte [0xb8001], 0x0F     ; Атрибут: белый текст на чёрном фоне
    ; --------------------------------------------------------------

    ; "jmp 0x1000" с числовым литералом (не меткой) NASM кодирует как
    ; relative near jump, посчитанный под org 0x7c00 - корректно ТОЛЬКО
    ; если этот jmp физически выполняется по 0x7c00+смещение. После
    ; самоперемещения (см. начало файла) этот код реально работает с
    ; релоцированной копии (0x0600+смещение), а цель (ядро на 0x1000)
    ; НЕ переехала вместе с копией - относительное смещение для пары
    ; "переехавший jmp -> неподвижная цель" в итоге неверное, прыжок
    ; улетает не туда. mov+jmp eax - абсолютный переход, не зависит от
    ; org/релокации вообще.
    mov eax, 0x1000
    jmp eax
    
; --- Сигнатура загрузочного сектора ---
times 510 - ($ - $$) db 0  
dw 0xAA55