; =================================================================
;  Точка входа пользовательской программы
; =================================================================
;
; Загрузчик (команда "run" в kernel.c) копирует плоский бинарник
; этой программы по адресу 0x100000 и передаёт на него управление
; через task_create_user_isolated(). _start должен быть первым байтом
; файла (как _start в kernel_entry.asm для kernel.bin) — за это отвечает
; порядок объектных файлов в команде ld в build.bat.
;
; Если user_main() возвращается (нормальное завершение программы -
; например, exitdemo.c), сообщаем ядру об этом через SYS_EXIT (0x06,
; см. syscall.h): schedule() уберёт задачу из кольца и освободит её слот.
; .hang после int 0x80 нужен на случай, если задача всё же продолжит
; выполняться до следующего тика таймера (для hello.c этот код
; недостижим - её user_main() не возвращается).

[bits 32]

global _start
extern _user_main

_start:
    call _user_main
    mov ah, 0x06    ; SYS_EXIT
    int 0x80
.hang:
    jmp .hang
