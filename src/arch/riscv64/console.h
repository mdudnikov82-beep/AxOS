#pragma once

// Простая графическая консоль поверх virtio-gpu framebuffer: сетка
// GPU_FB_WIDTH/8 x GPU_FB_HEIGHT/8 символов (100x75 при 800x600), 8x8
// битмап-шрифт, курсор, прокрутка, и минимальный набор ANSI-escape'ов —
// именно те, что реально использует AxSH и юзер-программы:
//   \033[0m, \033[1;36m, \033[32m, \033[33m (цвет / reset)
//   \033[2J (очистить экран), \033[H (курсор в (0,0)), \033[K (очистить до конца строки)
// Всё остальное (неизвестные esc-последовательности) молча проглатывается.

// Очищает экран, сбрасывает курсор в (0,0) и цвет в белый.
void console_init(void);

// Пишет len байт из buf на графическую консоль (интерпретируя \r \n
// backspace и вышеперечисленные ANSI-коды), затем один раз flush'ит
// фреймбуфер на экран. Не делает ничего, если GPU не готов.
void console_write(const char *buf, unsigned long len);
