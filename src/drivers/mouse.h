#ifndef MOUSE_H
#define MOUSE_H

// Инициализирует вторичный канал контроллера 8042 (AUX/мышь): включает
// порт, IRQ12 и тактирование, переводит мышь в режим потоковой отправки
// пакетов (см. mouse.c). Вызывать после init_idt() - IRQ12 уже должен
// быть размаскирован на PIC к этому моменту.
void init_mouse();

// Обработчик IRQ12 (вызывается из idt.asm на каждый байт пакета мыши -
// не на весь пакет; накопление состояния - внутри mouse.c).
void mouse_irq_handler_main();

// Текущее положение курсора, ограниченное сеткой 80x25 (текстовый режим) -
// и битовая маска нажатых кнопок (бит0=левая, бит1=правая, бит2=средняя).
int mouse_get_x();
int mouse_get_y();
int mouse_get_buttons();

#endif
